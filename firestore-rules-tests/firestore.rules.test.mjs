function menuSeedId(collectionName) {
  switch (collectionName) {
    case 'weekly_menus':
      return MENU_WEEK_ID;
    case 'menu_entries':
      return 'menu-entry-seed';
    case 'menu_templates':
      return MENU_TEMPLATE_ID;
    case 'menu_template_entries':
      return 'menu-template-entry-seed';
    case 'daily_assignments':
      return 'daily-assignment-seed';
    default:
      throw new Error(`Unknown menu collection: ${collectionName}`);
  }
}
