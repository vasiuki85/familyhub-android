test('task visibility queries return public own-private and assigned-private only', async () => {
  const carol = env.authenticatedContext('carol').firestore();
  const tasksRef = collection(carol, 'families/family-a/tasks');

  const publicTasks = await assertSucceeds(getDocs(
    query(tasksRef, where('private', '==', false)),
  ));
  const ownPrivateTasks = await assertSucceeds(getDocs(
    query(
      tasksRef,
      where('private', '==', true),
      where('createdByUserId', '==', 'carol'),
    ),
  ));
  const assignedPrivateTasks = await assertSucceeds(getDocs(
    query(
      tasksRef,
      where('private', '==', true),
      where('assignedToUserId', '==', 'carol'),
    ),
  ));

  const mergedIds = new Set([
    ...publicTasks.docs.map((snapshot) => snapshot.id),
    ...ownPrivateTasks.docs.map((snapshot) => snapshot.id),
    ...assignedPrivateTasks.docs.map((snapshot) => snapshot.id),
  ]);

  assert.equal(mergedIds.has('task-public'), true);
  assert.equal(mergedIds.has('task-own-private'), true);
  assert.equal(mergedIds.has('task-assigned-private'), true);
  assert.equal(mergedIds.has('task-foreign-private'), false);
});

