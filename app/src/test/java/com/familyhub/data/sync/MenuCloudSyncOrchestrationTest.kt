/**
 * Integration-style orchestration coverage for menu cloud sync phases.
 * Wires merge → upload planning → sync decisions → tombstone verification without weakening production APIs.
 */
class MenuCloudSyncOrchestrationTest {

    private val userId = "user-parent"
    private val weekStart = 1_700_000_000_000L
    private val canonicalWeekId = MenuSyncIds.weeklyMenuId(weekStart)

    @Test
    fun parentAliasRepair_orchestrationPlansWritesWithAuthoritativeSelfRole() {
        val remoteAlias = weeklyMenu("alias-week")
        val localCanonical = weeklyMenu(canonicalWeekId)
        val remoteMember = ExportMember(
            id = userId,
            displayName = "Remote",
            roleLabel = "Parent",
            avatarColor = "#222",
            role = MemberRole.PARENT.name,
        )
        val localMember = ExportMember(
            id = userId,
            displayName = "Local",
            roleLabel = "Child",
            avatarColor = "#111",
            role = MemberRole.CHILD.name,
        )

        val pipeline = runMenuSyncPipeline(
            local = ExportData(weeklyMenus = listOf(localCanonical), members = listOf(localMember)),
            remote = ExportData(weeklyMenus = listOf(remoteAlias), members = listOf(remoteMember)),
            currentUserId = userId,
            hasPendingChanges = false,
        )

        assertTrue(pipeline.context.canUploadMenu)
        assertTrue(pipeline.context.operations.isNotEmpty())
        assertTrue(
            pipeline.context.operations.any {
                it is MenuCloudWriteOperation.Delete && it.documentId == "alias-week"
            },
        )
        assertTrue(
            pipeline.context.operations.any {
                it is MenuCloudWriteOperation.Set && it.documentId == canonicalWeekId
            },
        )
        assertEquals(MemberRole.PARENT.name, requireNotNull(pipeline.selfForUpload).role)
        assertTrue(pipeline.decisions.uploadRequired)
        assertTrue(pipeline.decisions.shouldRunUploadTransaction)
    }

    @Test
    fun childSync_orchestrationImportsRemoteWithoutMenuWrites() {
        val remoteMenu = weeklyMenu(canonicalWeekId, updatedAt = 9L)
        val localMenu = weeklyMenu(canonicalWeekId, updatedAt = 1L)
        val childId = "child-user"
        val childMember = ExportMember(
            id = childId,
            displayName = "Child",
            roleLabel = "Child",
            avatarColor = "#fff",
            role = MemberRole.CHILD.name,
        )

        val pipeline = runMenuSyncPipeline(
            local = ExportData(weeklyMenus = listOf(localMenu), members = listOf(childMember)),
            remote = ExportData(weeklyMenus = listOf(remoteMenu), members = listOf(childMember)),
            currentUserId = childId,
            hasPendingChanges = false,
        )

        assertFalse(pipeline.context.canUploadMenu)
        assertTrue(pipeline.context.operations.isEmpty())
        assertEquals(remoteMenu, pipeline.mergedForLocal.weeklyMenus.single())
        assertFalse(pipeline.decisions.menuCloudNeedsWrite)
        assertFalse(pipeline.decisions.shouldRunUploadTransaction)
    }

    @Test
    fun malformedRemoteDecode_abortsBeforeMergeUploadOrConfirmation() {
        val valid = MenuFirestoreRawDocument(
            collection = DeletedCloudDocumentCollections.WEEKLY_MENUS,
            documentId = canonicalWeekId,
            fields = mapOf(
                "id" to canonicalWeekId,
                "startDateMillis" to weekStart,
                "isAutoGenerated" to false,
                "createdAt" to 1L,
                "updatedAt" to 1L,
            ),
        )
        val malformed = MenuFirestoreRawDocument(
            collection = DeletedCloudDocumentCollections.WEEKLY_MENUS,
            documentId = "bad",
            fields = mapOf("id" to "bad", "startDateMillis" to -1L),
        )
        assertThrows(MenuFirestoreDocumentCodecException::class.java) {
            MenuFirestoreDocumentCodec.decodeSnapshot(listOf(valid, malformed))
        }

        val source = readSyncRepositorySource()
        assertTrue(source.contains("isMalformedMenuSnapshot"))
        assertTrue(source.contains("Aborting sync without import/upload"))
        assertTrue(source.contains("MenuFirestoreDocumentCodecException"))
    }

    @Test
    fun verificationOnly_orchestrationSkipsUploadButRequiresServerVerification() {
        val context = MenuCloudUploadContext(
            capability = MenuCloudWriteCapabilityResult(canUploadMenu = true, readOnlyReason = null),
            operations = emptyList(),
        )
        val decisions = evaluateMenuCloudSyncDecisions(
            datedLocal = ExportData(),
            remoteData = ExportData(),
            mergedForLocal = ExportData(),
            menuUploadContext = context,
            hasPendingChanges = false,
            remoteAvailable = true,
            isCreatingFamily = false,
            stagedMenuTombstonesPresent = true,
            normalizedForComparison = { it },
        )

        assertTrue(decisions.verificationOnly)
        assertFalse(decisions.shouldRunUploadTransaction)
        assertTrue(decisions.verificationDownloadRequired)

        val source = readSyncRepositorySource()
        assertTrue(source.contains("verificationOnly"))
        assertTrue(source.contains("writable menu tombstone verification without upload transaction"))
        assertEquals(Source.SERVER, FirestoreBackendApi.syncDownloadFirestoreSource())
    }

    @Test
    fun orphanAmbiguity_orchestrationPreservesTombstoneInBatch() {
        val orphan = ExportMenuEntry(
            id = "orphan-entry",
            menuId = "missing-parent",
            dayOfWeek = 1,
            mealType = "BREAKFAST",
            servings = 2,
        )
        val rawRemote = MenuCloudSnapshot(menuEntries = listOf(orphan))
        val ambiguous = DeletedCloudDocument(
            "family",
            DeletedCloudDocumentCollections.MENU_ENTRIES,
            MenuSyncIds.menuEntryId(weekStart, 1, "BREAKFAST"),
        )
        val absent = DeletedCloudDocument(
            "family",
            DeletedCloudDocumentCollections.WEEKLY_MENUS,
            "gone-week",
        )

        val confirmed = menuTombstonesConfirmedAbsentOnRawRemote(rawRemote, setOf(ambiguous, absent))
        assertEquals(setOf(absent), confirmed)
        assertFalse(confirmed.contains(ambiguous))
    }

    @Test
    fun verifiedDeletion_orchestrationClearsTombstoneBatch() {
        val tombstone = DeletedCloudDocument(
            "family",
            DeletedCloudDocumentCollections.WEEKLY_MENUS,
            "alias-week",
        )
        val confirmed = menuTombstonesConfirmedAbsentOnRawRemote(MenuCloudSnapshot(), setOf(tombstone))
        assertEquals(setOf(tombstone), confirmed)
    }

    @Test
    fun outboxDeletes_mapAllLogicalMenuKeysToCloudCollections() {
        val tombstones = menuTombstonesFrom(
