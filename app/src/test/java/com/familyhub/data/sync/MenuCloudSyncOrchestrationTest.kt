        )
    }

    @Test
    fun outboxWeeklyDelete_removesRemoteAndPlansCloudDelete() {
        val admin = MenuCloudMemberRef(userId, MemberRole.ADMIN)
        val menuResult = mergeMenuCloud(
            localSnapshot = MenuCloudSnapshot(),
            remoteSnapshot = MenuCloudSnapshot(
                weeklyMenus = listOf(weeklyMenu(canonicalWeekId))
            ),
            tombstones = menuTombstonesFrom(
                deletedDocuments = emptySet(),
                pendingDeletedEntityIdsByCollection = mapOf(
                    "weeklyMenus" to setOf(canonicalWeekId)
                ),
            ),
            currentUserId = userId,
            remoteSelfMember = admin,
            localSelfMember = admin,
        )

        val context = buildMenuCloudUploadContext(menuResult)

        assertTrue(menuResult.localProjection.weeklyMenus.isEmpty())
        assertEquals(
            listOf(
                MenuCloudWriteOperation.Delete(
                    DeletedCloudDocumentCollections.WEEKLY_MENUS,
                    canonicalWeekId,
                )
            ),
            context.operations,
        )
    }

    @Test
    fun uploadFailure_syncRepositorySourceContract_importsOnlyAfterUploadPath() {
        val source = readSyncRepositorySource()
        val uploadIndex = source.indexOf("backendApi.uploadSnapshot(")
        val importIndex = source.indexOf(
            "importService.importData(",
            startIndex = uploadIndex.coerceAtLeast(0),
        )
        require(uploadIndex >= 0) { "uploadSnapshot call missing" }
        require(importIndex >= 0) { "importData call missing" }
        assertTrue("import must follow upload in sync flow", importIndex > uploadIndex)

        val uploadBlock = extractBetween(source, "if (shouldRunUploadTransaction)", "importService.importData")
        assertTrue(uploadBlock.contains("backendApi.uploadSnapshot("))
        assertFalse(uploadBlock.contains("importService.importData"))
    }

    @Test
    fun divergentCreatedAt_mergeAndUploadPlan_useRemoteImmutableCreatedAt() {
        val adminMember = adminMember(userId)
        val remoteCanonical = weeklyMenu(
            id = canonicalWeekId,
            updatedAt = 100L,
            createdAt = 1_000L,
            isAutoGenerated = false,
        )
        val localCanonical = weeklyMenu(
            id = canonicalWeekId,
            updatedAt = 200L,
            createdAt = 2_000L,
            isAutoGenerated = true,
        )
        val pipeline = runMenuSyncPipeline(
            local = ExportData(weeklyMenus = listOf(localCanonical), members = listOf(adminMember)),
            remote = ExportData(weeklyMenus = listOf(remoteCanonical), members = listOf(adminMember)),
            currentUserId = userId,
            hasPendingChanges = false,
        )

        assertEquals(200L, pipeline.mergedForLocal.weeklyMenus.single().updatedAt)
        assertTrue(pipeline.mergedForLocal.weeklyMenus.single().isAutoGenerated)
        assertEquals(1_000L, pipeline.mergedForLocal.weeklyMenus.single().createdAt)
        assertTrue(pipeline.context.operations.isNotEmpty())
        val set = pipeline.context.operations
            .filterIsInstance<MenuCloudWriteOperation.Set>()
            .single { it.documentId == canonicalWeekId }
        assertEquals(1_000L, set.fields["createdAt"])
        assertEquals(200L, set.fields["updatedAt"])
        assertEquals(true, set.fields["isAutoGenerated"])
    }

    @Test
    fun divergentCreatedAt_secondSyncAfterRepairedRemote_isNoOp() {
        val adminMember = adminMember(userId)
        val remoteCanonical = weeklyMenu(
            id = canonicalWeekId,
            updatedAt = 100L,
            createdAt = 1_000L,
            isAutoGenerated = false,
        )
        val localCanonical = weeklyMenu(
            id = canonicalWeekId,
            updatedAt = 200L,
            createdAt = 2_000L,
            isAutoGenerated = true,
        )
        val first = runMenuSyncPipeline(
            local = ExportData(weeklyMenus = listOf(localCanonical), members = listOf(adminMember)),
            remote = ExportData(weeklyMenus = listOf(remoteCanonical), members = listOf(adminMember)),
            currentUserId = userId,
            hasPendingChanges = false,
        )
        assertEquals(1_000L, first.mergedForLocal.weeklyMenus.single().createdAt)

        val repairedRemote = ExportData(
            weeklyMenus = listOf(
                weeklyMenu(
                    id = canonicalWeekId,
                    updatedAt = 200L,
                    createdAt = 1_000L,
                    isAutoGenerated = true,
                ),
            ),
            members = listOf(adminMember),
        )
        val second = runMenuSyncPipeline(
            local = ExportData(
                weeklyMenus = listOf(first.mergedForLocal.weeklyMenus.single()),
                members = listOf(adminMember),
            ),
            remote = repairedRemote,
            currentUserId = userId,
            hasPendingChanges = false,
        )

        assertTrue(second.context.operations.isEmpty())
        assertFalse(second.decisions.uploadRequired)
        assertEquals(1_000L, second.mergedForLocal.weeklyMenus.single().createdAt)
    }

    @Test
    fun secondSyncAfterRepair_orchestrationIsNoOp() {
        val adminMember = adminMember(userId)
        val first = runMenuSyncPipeline(
            local = ExportData(weeklyMenus = listOf(weeklyMenu(canonicalWeekId)), members = listOf(adminMember)),
            remote = ExportData(weeklyMenus = listOf(weeklyMenu("alias-week")), members = listOf(adminMember)),
            currentUserId = userId,
            hasPendingChanges = false,
        )
        assertTrue(first.decisions.uploadRequired)

        val repairedRemote = ExportData(weeklyMenus = listOf(weeklyMenu(canonicalWeekId)), members = listOf(adminMember))
        val second = runMenuSyncPipeline(
            local = ExportData(weeklyMenus = listOf(weeklyMenu(canonicalWeekId)), members = listOf(adminMember)),
            remote = repairedRemote,
            currentUserId = userId,
            hasPendingChanges = false,
        )

        assertTrue(second.context.operations.isEmpty())
        assertFalse(second.decisions.menuCloudNeedsWrite)
        assertFalse(second.decisions.shouldRunUploadTransaction)
        assertFalse(second.decisions.uploadRequired)
    }

    private data class MenuSyncPipelineResult(
        val mergedForLocal: ExportData,
        val context: MenuCloudUploadContext,
        val decisions: MenuCloudSyncDecisions,
        val selfForUpload: ExportMember?,
    )

    private fun runMenuSyncPipeline(
        local: ExportData,
        remote: ExportData,
        currentUserId: String,
        hasPendingChanges: Boolean,
    ): MenuSyncPipelineResult {
        val localMenu = local.toMenuCloudSnapshot()
        val remoteMenu = remote.toMenuCloudSnapshot()
        val remoteSelf = remote.members.find { it.id == currentUserId }?.toMenuCloudMemberRef()
        val localSelf = local.members.find { it.id == currentUserId }?.toMenuCloudMemberRef()
        val menuResult = mergeMenuCloud(
            localSnapshot = localMenu,
            remoteSnapshot = remoteMenu,
            tombstones = emptyList(),
            currentUserId = currentUserId,
            remoteSelfMember = remoteSelf,
            localSelfMember = localSelf,
        )
        val context = buildMenuCloudUploadContext(menuResult)
        val mergedForLocal = local.withoutMenuFields().withMenuSnapshot(menuResult.localProjection)
        val decisions = evaluateMenuCloudSyncDecisions(
            datedLocal = local,
            remoteData = remote,
            mergedForLocal = mergedForLocal,
            menuUploadContext = context,
            hasPendingChanges = hasPendingChanges,
            remoteAvailable = true,
            isCreatingFamily = false,
            stagedMenuTombstonesPresent = false,
            normalizedForComparison = { it },
        )
        val selfForUpload = selfMemberForUpload(
            local.members.find { it.id == currentUserId },
            remote.members.find { it.id == currentUserId },
        )
        return MenuSyncPipelineResult(
            mergedForLocal = mergedForLocal,
            context = context,
            decisions = decisions,
            selfForUpload = selfForUpload,
        )
    }

    private fun weeklyMenu(
        id: String,
        updatedAt: Long = 1L,
        createdAt: Long = 1L,
        isAutoGenerated: Boolean = false,
    ): ExportWeeklyMenu {
        return ExportWeeklyMenu(
            id = id,
            startDateMillis = weekStart,
            isAutoGenerated = isAutoGenerated,
            createdAt = createdAt,
            updatedAt = updatedAt,
        )
    }

    private fun adminMember(id: String): ExportMember {
        return ExportMember(
            id = id,
            displayName = "Admin",
            roleLabel = "Admin",
            avatarColor = "#fff",
            role = MemberRole.ADMIN.name,
        )
    }

    private fun readSyncRepositorySource(): String {
        val candidates = listOf(
            "app/src/main/java/com/familyhub/data/sync/SyncRepository.kt",
            "src/main/java/com/familyhub/data/sync/SyncRepository.kt",
        )
        val path = candidates.first { Files.exists(Paths.get(it)) }
        return String(Files.readAllBytes(Paths.get(path)), StandardCharsets.UTF_8)
    }

    private fun extractBetween(source: String, startMarker: String, endMarker: String): String {
        val start = source.indexOf(startMarker)
        val end = source.indexOf(endMarker, start)
        require(start >= 0 && end > start) { "Markers not found: $startMarker .. $endMarker" }
        return source.substring(start, end)
    }
