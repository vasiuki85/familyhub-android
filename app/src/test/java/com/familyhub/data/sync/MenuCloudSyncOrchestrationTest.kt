                MenuCloudTombstone(DeletedCloudDocumentCollections.MENU_TEMPLATE_ENTRIES, "template-entry"),
                MenuCloudTombstone(DeletedCloudDocumentCollections.DAILY_ASSIGNMENTS, "assignment"),
