    @Test
    fun malformedDocument_rejectsEntireDecodeSnapshot() {
        val valid = MenuFirestoreRawDocument(
            collection = DeletedCloudDocumentCollections.WEEKLY_MENUS,
            documentId = canonicalWeekId,
            fields = mapOf(
                "id" to canonicalWeekId,
                "startDateMillis" to weekStart,
                "isAutoGenerated" to false,
                "createdAt" to 1L,
                "updatedAt" to 1L,
            ),
        )
        val malformed = MenuFirestoreRawDocument(
            collection = DeletedCloudDocumentCollections.WEEKLY_MENUS,
            documentId = "bad",
            fields = mapOf("id" to "bad", "startDateMillis" to -1L),
        )
        assertThrows(MenuFirestoreDocumentCodecException::class.java) {
            MenuFirestoreDocumentCodec.decodeSnapshot(listOf(valid, malformed))
        }
    }

