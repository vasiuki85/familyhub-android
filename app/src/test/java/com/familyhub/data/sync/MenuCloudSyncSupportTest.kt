    @Test
    fun canonicalRepairUpload_isIdempotentOnSecondPlan() {
        val menuResult = mergeMenuCloud(
            localSnapshot = MenuCloudSnapshot(weeklyMenus = listOf(weeklyMenu(canonicalWeekId))),
            remoteSnapshot = MenuCloudSnapshot(weeklyMenus = listOf(weeklyMenu("alias-week"))),
            tombstones = emptyList(),
            currentUserId = userId,
            remoteSelfMember = MenuCloudMemberRef(userId, MemberRole.ADMIN),
            localSelfMember = MenuCloudMemberRef(userId, MemberRole.ADMIN),
        )
        val first = buildMenuCloudUploadContext(menuResult)
        assertTrue(first.operations.isNotEmpty())
        val repairedRemote = MenuCloudSnapshot(weeklyMenus = listOf(weeklyMenu(canonicalWeekId)))
        val secondResult = mergeMenuCloud(
            localSnapshot = MenuCloudSnapshot(weeklyMenus = listOf(weeklyMenu(canonicalWeekId))),
            remoteSnapshot = repairedRemote,
            tombstones = emptyList(),
            currentUserId = userId,
            remoteSelfMember = MenuCloudMemberRef(userId, MemberRole.ADMIN),
            localSelfMember = MenuCloudMemberRef(userId, MemberRole.ADMIN),
        )
        val second = buildMenuCloudUploadContext(secondResult)
        assertTrue(second.operations.isEmpty())
    }

