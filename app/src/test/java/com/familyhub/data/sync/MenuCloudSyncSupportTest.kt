    @Test
    fun combinedTaskAndMenuBoundary_allows499DocumentOpsPlusUpdatedAt() {
        val taskOps = (1..498).map { index ->
            PlannedUploadOperation.Set("tasks", "task-$index", ExportTask(id = "task-$index", title = "T$index"))
        }
        val menuOps = listOf(
            MenuCloudWriteOperation.Set(
