package com.familyhub.data.menu.firestore

import com.familyhub.data.datastore.DeletedCloudDocumentCollections
import com.familyhub.data.export.ExportDailyAssignment
import com.familyhub.data.export.ExportMenuEntry
import com.familyhub.data.export.ExportMenuTemplate
import com.familyhub.data.export.ExportMenuTemplateEntry
import com.familyhub.data.export.ExportWeeklyMenu
import com.familyhub.domain.utils.MenuSyncIds
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test

class MenuFirestoreDocumentCodecTest {

    private val weekStart = 1_700_000_000_000L
    private val canonicalParentId = MenuSyncIds.weeklyMenuId(weekStart)
    private val canonicalEntryId = MenuSyncIds.menuEntryId(weekStart, 0, "BREAKFAST")
    private val templateId = "menu-template-codec"
    private val canonicalTemplateEntryId = MenuSyncIds.menuTemplateEntryId(templateId, 0, "LUNCH")
    private val canonicalDailyId = MenuSyncIds.dailyAssignmentId(weekStart, 0)

    @Test
    fun weeklyMenu_roundTrip() {
        val menu = ExportWeeklyMenu(
            id = canonicalParentId,
            startDateMillis = weekStart,
            isAutoGenerated = false,
            createdAt = 1L,
            updatedAt = 2L,
        )
        val encoded = MenuFirestoreDocumentCodec.encodeWeeklyMenu(menu)
        val decoded = MenuFirestoreDocumentCodec.decodeWeeklyMenu(canonicalParentId, encoded)
        assertEquals(menu, decoded)
    }

    @Test
    fun menuTemplate_roundTrip() {
        val template = ExportMenuTemplate(
            id = templateId,
            name = "Weeknight staples",
            createdAt = 1L,
            updatedAt = 2L,
        )
        val encoded = MenuFirestoreDocumentCodec.encodeMenuTemplate(template)
        val decoded = MenuFirestoreDocumentCodec.decodeMenuTemplate(templateId, encoded)
        assertEquals(template, decoded)
    }

    @Test
    fun menuTemplateEntry_roundTrip() {
        val entry = ExportMenuTemplateEntry(
            id = canonicalTemplateEntryId,
            templateId = templateId,
            dayOfWeek = 0,
            mealType = "LUNCH",
            customDish = "Суп",
            servings = 2,
            updatedAt = 2L,
        )
        val encoded = MenuFirestoreDocumentCodec.encodeMenuTemplateEntry(entry)
        val decoded = MenuFirestoreDocumentCodec.decodeMenuTemplateEntry(canonicalTemplateEntryId, encoded)
        assertEquals(entry.copy(cookingTaskId = null, prepTaskId = null), decoded)
    }

    @Test
    fun dailyAssignment_roundTrip() {
        val assignment = ExportDailyAssignment(
            id = canonicalDailyId,
            weekStartMillis = weekStart,
            dayOfWeek = 0,
            assignedMemberId = "member-a",
            rewardPoints = 5,
            isRated = true,
            updatedAt = 2L,
        )
        val encoded = MenuFirestoreDocumentCodec.encodeDailyAssignment(assignment)
        val decoded = MenuFirestoreDocumentCodec.decodeDailyAssignment(canonicalDailyId, encoded)
        assertEquals(assignment, decoded)
    }

    @Test
    fun menuEntry_roundTrip_preservesAliasId() {
        val entry = ExportMenuEntry(
            id = "alias-entry",
            menuId = "alias-parent",
            dayOfWeek = 0,
            mealType = "BREAKFAST",
            customDish = "Борщ",
            servings = 2,
            updatedAt = 3L,
        )
        val encoded = MenuFirestoreDocumentCodec.encodeMenuEntry(entry)
        val decoded = MenuFirestoreDocumentCodec.decodeMenuEntry("alias-entry", encoded)
        assertEquals(entry, decoded)
    }

    @Test
    fun menuTemplateEntry_decodedTaskRefsAlwaysNull() {
        val entry = ExportMenuTemplateEntry(
            id = "tpl-entry",
            templateId = "tpl-1",
            dayOfWeek = 0,
            mealType = "LUNCH",
            servings = 2,
            updatedAt = 1L,
        )
        val encoded = MenuFirestoreDocumentCodec.encodeMenuTemplateEntry(entry)
        assertFalse(encoded.containsKey("cookingTaskId"))
        assertFalse(encoded.containsKey("prepTaskId"))
        val decoded = MenuFirestoreDocumentCodec.decodeMenuTemplateEntry("tpl-entry", encoded)
        assertNull(decoded.cookingTaskId)
        assertNull(decoded.prepTaskId)
    }

    @Test
    fun optionalFields_absentAndNull() {
        val entry = mapOf(
            "id" to "entry-1",
            "menuId" to canonicalParentId,
            "dayOfWeek" to 0L,
            "mealType" to "BREAKFAST",
            "servings" to 2L,
            "updatedAt" to 1L,
            "recipeId" to null,
        )
        val decoded = MenuFirestoreDocumentCodec.decodeMenuEntry("entry-1", entry)
        assertNull(decoded.recipeId)
    }

    @Test
    fun rejectUnknownField() {
        val fields = weeklyFields() + ("extra" to "nope")
        assertCodecException {
            MenuFirestoreDocumentCodec.decodeWeeklyMenu(canonicalParentId, fields)
        }
    }

    @Test
    fun rejectMissingRequiredField() {
        val fields = weeklyFields().toMutableMap()
        fields.remove("createdAt")
        assertCodecException {
            MenuFirestoreDocumentCodec.decodeWeeklyMenu(canonicalParentId, fields)
        }
    }

    @Test
    fun rejectDoubleInsteadOfInteger() {
        val fields = weeklyFields().toMutableMap()
        fields["updatedAt"] = 1.5
        assertCodecException {
            MenuFirestoreDocumentCodec.decodeWeeklyMenu(canonicalParentId, fields)
        }
    }

    @Test
    fun rejectIntegerOutsideIntRangeForServingsField() {
        val fields = menuEntryFields().toMutableMap()
        fields["servings"] = (Int.MAX_VALUE.toLong() + 1L)
        assertCodecException {
            MenuFirestoreDocumentCodec.decodeMenuEntry("entry-1", fields)
        }
    }

    @Test
    fun rejectIdDocIdMismatch() {
        assertCodecException {
            MenuFirestoreDocumentCodec.decodeWeeklyMenu("other-id", weeklyFields())
        }
    }

    @Test
    fun rejectTemplateEntryNonNullTaskRefsOnDecode() {
        val fields = templateEntryFields().toMutableMap()
        fields["cookingTaskId"] = "cook"
        assertCodecException {
            MenuFirestoreDocumentCodec.decodeMenuTemplateEntry("tpl-entry", fields)
        }
    }

    @Test
    fun rejectTemplateEntryNonNullTaskRefsOnEncode() {
        assertCodecException {
            MenuFirestoreDocumentCodec.encodeMenuTemplateEntry(
                ExportMenuTemplateEntry(
                    id = canonicalTemplateEntryId,
                    templateId = templateId,
                    dayOfWeek = 0,
                    mealType = "LUNCH",
                    servings = 2,
                    cookingTaskId = "task-a",
                    updatedAt = 1L,
                ),
            )
        }
    }

    @Test
    fun decodeSnapshot_preservesAliasIds() {
        val snapshot = MenuFirestoreDocumentCodec.decodeSnapshot(
            listOf(
                MenuFirestoreRawDocument(
                    DeletedCloudDocumentCollections.WEEKLY_MENUS,
                    "alias-week",
                    weeklyFields(id = "alias-week"),
                ),
            ),
        )
        assertEquals("alias-week", snapshot.weeklyMenus.single().id)
    }

    @Test
    fun encodeOutput_containsOnlyAllowedKeys() {
        val encoded = MenuFirestoreDocumentCodec.encodeMenuEntry(
            ExportMenuEntry(
                id = "entry-1",
                menuId = canonicalParentId,
                dayOfWeek = 0,
                mealType = "BREAKFAST",
                customDish = "toast",
                servings = 2,
                updatedAt = 1L,
            ),
        )
        assertEquals(
            setOf("id", "menuId", "dayOfWeek", "mealType", "servings", "updatedAt", "customDish"),
            encoded.keys,
        )
    }

    @Test
    fun rejectInvalidFirestoreReferenceIdOnDecode() {
        val fields = menuEntryFields().toMutableMap()
        fields["menuId"] = ""
        assertCodecException {
            MenuFirestoreDocumentCodec.decodeMenuEntry("entry-1", fields)
        }
    }

    @Test
    fun rejectInvalidFirestoreReferenceIdOnEncode() {
        assertCodecException {
            MenuFirestoreDocumentCodec.encodeMenuEntry(
                ExportMenuEntry(
                    id = "entry-1",
                    menuId = "",
                    dayOfWeek = 0,
                    mealType = "BREAKFAST",
                    servings = 2,
                    updatedAt = 1L,
                ),
            )
        }
    }

    @Test
    fun rejectInvalidMealTypeAndDayOfWeek() {
        val badMeal = menuEntryFields().toMutableMap().apply { put("mealType", "BRUNCH") }
        assertCodecException {
            MenuFirestoreDocumentCodec.decodeMenuEntry("entry-1", badMeal)
        }
        val badDay = menuEntryFields().toMutableMap().apply { put("dayOfWeek", 7L) }
        assertCodecException {
            MenuFirestoreDocumentCodec.decodeMenuEntry("entry-1", badDay)
        }
    }

    @Test
    fun encodeRecord_rejectsWrongCollectionRecordPair() {
        assertCodecException {
            MenuFirestoreDocumentCodec.encodeRecord(
                DeletedCloudDocumentCollections.WEEKLY_MENUS,
                ExportMenuEntry(
                    id = "entry-1",
                    menuId = canonicalParentId,
                    dayOfWeek = 0,
                    mealType = "BREAKFAST",
                    servings = 2,
                    updatedAt = 1L,
                ),
            )
        }
    }

    @Test
    fun encodeWeeklyMenu_rejectsNegativeTimestamp() {
        assertCodecException {
            MenuFirestoreDocumentCodec.encodeWeeklyMenu(
                ExportWeeklyMenu(
                    id = canonicalParentId,
                    startDateMillis = -1L,
                    isAutoGenerated = false,
                    createdAt = 1L,
                    updatedAt = 2L,
                ),
            )
        }
    }

    private fun assertCodecException(block: () -> Unit) {
        assertThrows(MenuFirestoreDocumentCodecException::class.java, block)
    }

    private fun weeklyFields(
        id: String = canonicalParentId,
    ): Map<String, Any?> = mapOf(
        "id" to id,
        "startDateMillis" to weekStart,
        "isAutoGenerated" to false,
        "createdAt" to 1L,
        "updatedAt" to 2L,
    )

    private fun menuEntryFields(): Map<String, Any?> = mapOf(
        "id" to "entry-1",
        "menuId" to canonicalParentId,
        "dayOfWeek" to 0L,
        "mealType" to "BREAKFAST",
        "servings" to 2L,
        "updatedAt" to 1L,
    )

    private fun templateEntryFields(): Map<String, Any?> = mapOf(
        "id" to "tpl-entry",
        "templateId" to "tpl-1",
        "dayOfWeek" to 0L,
        "mealType" to "BREAKFAST",
        "servings" to 2L,
        "updatedAt" to 1L,
    )
}
