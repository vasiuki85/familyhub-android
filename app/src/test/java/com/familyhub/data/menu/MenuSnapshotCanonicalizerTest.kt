    @Test
    fun legacyChildren_inheritOwnParentTimestamp_notWeekWinner() {
        // Parent A older (createdAt=10) carries the stronger child payload.
        // Parent B newer (createdAt=20) carries the weaker child payload.
        // Payload tie-break alone would favor A's child; inherited parent ts makes B win.
        val data = ExportData(
            weeklyMenus = listOf(
                ExportWeeklyMenu(id = "old-a", startDateMillis = 1000L, createdAt = 10L),
                ExportWeeklyMenu(id = "old-b", startDateMillis = 1000L, createdAt = 20L)
            ),
            menuEntries = listOf(
                ExportMenuEntry(
                    id = "child-a",
                    menuId = "old-a",
                    dayOfWeek = 0,
                    mealType = "BREAKFAST",
                    servings = 9,
                    customDish = "payload-favored",
                    recipeId = "zzz",
                    updatedAt = 0L
                ),
                ExportMenuEntry(
                    id = "child-b",
                    menuId = "old-b",
                    dayOfWeek = 0,
                    mealType = "BREAKFAST",
                    servings = 1,
                    customDish = "provenance-wins",
                    recipeId = null,
                    updatedAt = 0L
                ),
                ExportMenuEntry(
                    id = "lunch-a",
                    menuId = "old-a",
                    dayOfWeek = 1,
                    mealType = "LUNCH",
                    servings = 2,
                    customDish = "keep-lunch",
                    updatedAt = 0L
                )
            )
        )
        val result = MenuSnapshotCanonicalizer.canonicalize(data)
        assertEquals(2, result.menuEntries.size)
        val breakfast = result.menuEntries.single { it.dayOfWeek == 0 }
        assertEquals("provenance-wins", breakfast.customDish)
        assertEquals(20L, breakfast.updatedAt)
        val lunch = result.menuEntries.single { it.dayOfWeek == 1 }
        assertEquals("keep-lunch", lunch.customDish)
        assertEquals(10L, lunch.updatedAt)
    }

