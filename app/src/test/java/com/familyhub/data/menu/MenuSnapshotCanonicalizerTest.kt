    @Test
    fun comparator_permutationSelectWinner_commutative() {
        val a = ExportWeeklyMenu(
            id = "a",
            startDateMillis = 1L,
            isAutoGenerated = false,
            createdAt = 10L,
            updatedAt = 10L
        )
        val b = ExportWeeklyMenu(
            id = "b",
            startDateMillis = 1L,
            isAutoGenerated = true,
            createdAt = 10L,
            updatedAt = 10L
        )
        val c = ExportWeeklyMenu(
            id = "c",
            startDateMillis = 1L,
            isAutoGenerated = true,
            createdAt = 9L,
            updatedAt = 10L
        )
        val orders = listOf(
            listOf(a, b, c),
            listOf(c, b, a),
            listOf(b, a, c),
            listOf(c, a, b)
        )
        val winners = orders.map {
            MenuRecordComparator.selectWinner(it, MenuRecordComparator::compareWeeklyMenus)
        }
        assertTrue(winners.all { it.id == "a" })
    }

    @Test
    fun planner_parityWithCanonicalizer() {
        val legacy = LegacyMenuSnapshotV36(
            weeklyMenus = listOf(
                LegacyWeeklyMenuRow("old", 5000L, false, 8L),
                LegacyWeeklyMenuRow("old2", 5000L, true, 1L)
            ),
            menuEntries = listOf(
                LegacyMenuEntryRow(
                    id = "e1",
                    menuId = "old",
                    dayOfWeek = 0,
                    mealType = "BREAKFAST",
                    recipeId = null,
                    customDish = "soup",
                    servings = 2,
                    assignedMemberId = null,
                    cookingTaskId = "cook",
                    prepTaskId = "prep"
                ),
                LegacyMenuEntryRow(
                    id = "e2",
                    menuId = "old2",
                    dayOfWeek = 3,
                    mealType = "SNACK",
                    recipeId = "r1",
                    customDish = null,
                    servings = 1,
                    assignedMemberId = "m",
                    cookingTaskId = null,
                    prepTaskId = null
                )
            ),
            menuTemplates = listOf(LegacyMenuTemplateRow("tpl", "T", 1L)),
            menuTemplateEntries = listOf(
                LegacyMenuTemplateEntryRow(
                    id = "te",
                    templateId = "tpl",
                    dayOfWeek = 1,
                    mealType = "LUNCH",
                    recipeId = null,
                    customDish = "x",
                    servings = 1,
                    assignedMemberId = null,
                    cookingTaskId = "bad",
                    prepTaskId = "bad2"
                )
            ),
            dailyAssignments = listOf(
                LegacyDailyAssignmentRow("da", 5000L, 1, "m1", null, false)
            )
        )
        val planned = Migration36To37Planner.plan(legacy)
        val viaCanon = MenuSnapshotCanonicalizer.canonicalize(
            ExportData(
                weeklyMenus = legacy.weeklyMenus.map {
                    ExportWeeklyMenu(it.id, it.startDateMillis, it.isAutoGenerated, it.createdAt, 0L)
                },
                menuEntries = legacy.menuEntries.map {
                    ExportMenuEntry(
                        it.id, it.menuId, it.dayOfWeek, it.mealType, it.recipeId, it.customDish,
                        it.servings, it.assignedMemberId, it.cookingTaskId, it.prepTaskId, 0L
                    )
                },
                menuTemplates = legacy.menuTemplates.map {
                    ExportMenuTemplate(it.id, it.name, it.createdAt, 0L)
                },
                menuTemplateEntries = legacy.menuTemplateEntries.map {
                    ExportMenuTemplateEntry(
                        it.id, it.templateId, it.dayOfWeek, it.mealType, it.recipeId, it.customDish,
                        it.servings, it.assignedMemberId, it.cookingTaskId, it.prepTaskId, 0L
                    )
                },
                dailyAssignments = legacy.dailyAssignments.map {
                    ExportDailyAssignment(
                        it.id, it.weekStartMillis, it.dayOfWeek, it.assignedMemberId,
                        it.rewardPoints, it.isRated, 0L
                    )
                }
            )
        )
        assertEquals(viaCanon.weeklyMenus.map { it.id }, planned.weeklyMenus.map { it.id })
        assertEquals(viaCanon.menuEntries.map { it.id }, planned.menuEntries.map { it.id })
        assertEquals(viaCanon.menuTemplateEntries.map { it.id }, planned.menuTemplateEntries.map { it.id })
        assertNull(planned.menuTemplateEntries.single().cookingTaskId)
        assertEquals("cook", planned.menuEntries.single { it.dayOfWeek == 0 }.cookingTaskId)
    }

