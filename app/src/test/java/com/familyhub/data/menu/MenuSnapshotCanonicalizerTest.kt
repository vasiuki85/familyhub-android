    @Test
    fun duplicateWeek_preservesComplementarySlots() {
        val data = ExportData(
            weeklyMenus = listOf(
                ExportWeeklyMenu(id = "old-a", startDateMillis = 1000L, createdAt = 10L),
                ExportWeeklyMenu(
                    id = "old-b",
                    startDateMillis = 1000L,
                    isAutoGenerated = true,
                    createdAt = 5L
                )
            ),
            menuEntries = listOf(
                ExportMenuEntry(
                    id = "e-a",
                    menuId = "old-a",
                    dayOfWeek = 0,
                    mealType = "BREAKFAST",
                    servings = 2,
                    cookingTaskId = "cook-1",
                    prepTaskId = "prep-1"
                ),
                ExportMenuEntry(
                    id = "e-b",
                    menuId = "old-b",
                    dayOfWeek = 1,
                    mealType = "LUNCH",
                    servings = 3,
                    cookingTaskId = "cook-2",
                    prepTaskId = null
                )
            )
        )

        val result = MenuSnapshotCanonicalizer.canonicalize(data)
        val parentId = MenuSyncIds.weeklyMenuId(1000L)
        assertEquals(1, result.weeklyMenus.size)
        assertEquals(parentId, result.weeklyMenus.single().id)
        assertEquals(2, result.menuEntries.size)
        assertTrue(result.menuEntries.any { it.dayOfWeek == 0 && it.mealType == "BREAKFAST" })
        assertTrue(result.menuEntries.any { it.dayOfWeek == 1 && it.mealType == "LUNCH" })
        val breakfast = result.menuEntries.single { it.dayOfWeek == 0 }
        assertEquals("cook-1", breakfast.cookingTaskId)
        assertEquals("prep-1", breakfast.prepTaskId)
    }

