package com.familyhub.data.menu.cloud

import com.familyhub.data.export.ExportDailyAssignment
import com.familyhub.data.export.ExportMenuEntry
import com.familyhub.data.export.ExportMenuTemplate
import com.familyhub.data.export.ExportMenuTemplateEntry
import com.familyhub.data.export.ExportWeeklyMenu
import com.familyhub.domain.utils.MenuSyncIds
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Test

class MenuCloudUploadTargetPreflightTest {

    private val weekStart = 1_700_000_000_000L
    private val canonicalWeekId = MenuSyncIds.weeklyMenuId(weekStart)
    private val canonicalEntryId = MenuSyncIds.menuEntryId(weekStart, 0, "BREAKFAST")
    private val templateId = "menu-template-preflight"
    private val canonicalTemplateEntryId = MenuSyncIds.menuTemplateEntryId(templateId, 0, "LUNCH")
    private val canonicalDailyId = MenuSyncIds.dailyAssignmentId(weekStart, 0)

    @Test
    fun acceptsCanonicalTarget() {
        MenuCloudUploadTargetPreflight.validateOrThrow(
            MenuCloudSnapshot(
                weeklyMenus = listOf(weeklyMenu()),
                menuEntries = listOf(menuEntry()),
                menuTemplates = listOf(template()),
                menuTemplateEntries = listOf(templateEntry()),
                dailyAssignments = listOf(dailyAssignment()),
            ),
        )
    }

    @Test
    fun rejectsNonCanonicalWeeklyId() {
        val error = assertThrows(MenuCloudUploadPlanException::class.java) {
            MenuCloudUploadTargetPreflight.validateOrThrow(
                MenuCloudSnapshot(weeklyMenus = listOf(weeklyMenu(id = "alias-week"))),
            )
        }
        assertTrue(error.message!!.contains("not canonical"))
    }

    @Test
    fun rejectsOrphanMenuEntry() {
        val error = assertThrows(MenuCloudUploadPlanException::class.java) {
            MenuCloudUploadTargetPreflight.validateOrThrow(
                MenuCloudSnapshot(
                    weeklyMenus = emptyList(),
                    menuEntries = listOf(menuEntry()),
                ),
            )
        }
        assertTrue(error.message!!.contains("missing parent"))
    }

    @Test
    fun rejectsDuplicateMenuEntrySlot() {
        val error = assertThrows(MenuCloudUploadPlanException::class.java) {
            MenuCloudUploadTargetPreflight.validateOrThrow(
                MenuCloudSnapshot(
                    weeklyMenus = listOf(weeklyMenu()),
                    menuEntries = listOf(
                        menuEntry(),
                        menuEntry(),
                    ),
                ),
            )
        }
        assertTrue(error.message!!.contains("Duplicate logical key"))
    }

    @Test
    fun rejectsTemplateEntryTaskRefs() {
        val error = assertThrows(MenuCloudUploadPlanException::class.java) {
            MenuCloudUploadTargetPreflight.validateOrThrow(
                MenuCloudSnapshot(
                    menuTemplates = listOf(template()),
                    menuTemplateEntries = listOf(
                        templateEntry().copy(cookingTaskId = "task-a"),
                    ),
                ),
            )
        }
        assertTrue(error.message!!.contains("cookingTaskId"))
    }

    private fun weeklyMenu(id: String = canonicalWeekId) = ExportWeeklyMenu(
        id = id,
        startDateMillis = weekStart,
        isAutoGenerated = false,
        createdAt = 1L,
        updatedAt = 2L,
    )

    private fun menuEntry(id: String = canonicalEntryId) = ExportMenuEntry(
        id = id,
        menuId = canonicalWeekId,
        dayOfWeek = 0,
        mealType = "BREAKFAST",
        servings = 2,
        updatedAt = 2L,
    )

    private fun template() = ExportMenuTemplate(
        id = templateId,
        name = "Weeknight",
        createdAt = 1L,
        updatedAt = 2L,
    )

    private fun templateEntry() = ExportMenuTemplateEntry(
        id = canonicalTemplateEntryId,
        templateId = templateId,
        dayOfWeek = 0,
        mealType = "LUNCH",
        servings = 2,
        updatedAt = 2L,
    )

    private fun dailyAssignment() = ExportDailyAssignment(
        id = canonicalDailyId,
        weekStartMillis = weekStart,
        dayOfWeek = 0,
        isRated = false,
        updatedAt = 2L,
    )
}
