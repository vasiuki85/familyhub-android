package com.familyhub.data.menu

import com.familyhub.data.local.entity.MenuEntryEntity
import com.familyhub.data.local.entity.MenuTemplateEntity
import com.familyhub.data.local.entity.MenuTemplateEntryEntity
import com.familyhub.data.local.entity.MenuTemplateWithEntries
import com.familyhub.data.local.entity.WeeklyMenuEntity
import com.familyhub.data.local.entity.WeeklyMenuWithEntries
import com.familyhub.domain.utils.MenuMutationStaleException
import com.familyhub.domain.utils.MenuSyncIds
import org.junit.Assert.assertThrows
import org.junit.Test

class MenuMutationSnapshotGuardTest {

  private val weekStart = 1_700_000_000_000L
  private val canonicalParentId = MenuSyncIds.weeklyMenuId(weekStart)
  private val templateId = "tpl-1"

  @Test
  fun weekly_childInserted_detected() {
    val expected = weeklySnapshot(entries = listOf(entry(customDish = "Only")))
    val fresh = weeklySnapshot(
      entries = listOf(
        entry(customDish = "Only"),
        entry(day = 1, meal = "LUNCH", customDish = "Inserted", updatedAt = 10L),
      ),
    )
    assertThrows(MenuMutationStaleException::class.java) {
      MenuMutationSnapshotGuard.requireWeeklyAggregateUnchanged(expected, fresh)
    }
  }

  @Test
  fun weekly_childDeleted_detected() {
    val deleted = entry(day = 1, meal = "LUNCH", customDish = "Gone", updatedAt = 10L)
    val expected = weeklySnapshot(entries = listOf(entry(customDish = "Keep"), deleted))
    val fresh = weeklySnapshot(entries = listOf(entry(customDish = "Keep")))
    assertThrows(MenuMutationStaleException::class.java) {
      MenuMutationSnapshotGuard.requireWeeklyAggregateUnchanged(expected, fresh)
    }
  }

  @Test
  fun weekly_childPayloadDriftSameUpdatedAt_detected() {
    val expected = weeklySnapshot(entries = listOf(entry(customDish = "Before", updatedAt = 77L)))
    val fresh = weeklySnapshot(entries = listOf(entry(customDish = "After", updatedAt = 77L)))
    assertThrows(MenuMutationStaleException::class.java) {
      MenuMutationSnapshotGuard.requireWeeklyAggregateUnchanged(expected, fresh)
    }
  }

  @Test
  fun weekly_childUpdatedAtChanged_detected() {
    val expected = weeklySnapshot(entries = listOf(entry(customDish = "Same", updatedAt = 50L)))
    val fresh = weeklySnapshot(entries = listOf(entry(customDish = "Same", updatedAt = 99L)))
    assertThrows(MenuMutationStaleException::class.java) {
      MenuMutationSnapshotGuard.requireWeeklyAggregateUnchanged(expected, fresh)
    }
  }

  @Test
  fun weekly_parentPayloadDriftSameUpdatedAt_detected() {
    val expected = weeklySnapshot(
      parent = parent(updatedAt = 200L, isAutoGenerated = false),
      entries = emptyList(),
    )
    val fresh = weeklySnapshot(
      parent = parent(updatedAt = 200L, isAutoGenerated = true),
      entries = emptyList(),
    )
    assertThrows(MenuMutationStaleException::class.java) {
      MenuMutationSnapshotGuard.requireWeeklyAggregateUnchanged(expected, fresh)
    }
  }

  @Test
  fun template_childInserted_detected() {
    val expected = templateSnapshot(entries = listOf(templateEntry(customDish = "Only")))
    val fresh = templateSnapshot(
      entries = listOf(
        templateEntry(customDish = "Only"),
        templateEntry(day = 1, meal = "LUNCH", customDish = "Inserted", updatedAt = 10L),
      ),
    )
    assertThrows(MenuMutationStaleException::class.java) {
      MenuMutationSnapshotGuard.requireTemplateAggregateUnchanged(expected, fresh)
    }
  }

  @Test
  fun template_childDeleted_detected() {
    val deleted = templateEntry(day = 1, meal = "LUNCH", customDish = "Gone", updatedAt = 10L)
    val expected = templateSnapshot(
      entries = listOf(templateEntry(customDish = "Keep"), deleted),
    )
    val fresh = templateSnapshot(entries = listOf(templateEntry(customDish = "Keep")))
    assertThrows(MenuMutationStaleException::class.java) {
      MenuMutationSnapshotGuard.requireTemplateAggregateUnchanged(expected, fresh)
    }
  }

  @Test
  fun template_childPayloadDriftSameUpdatedAt_detected() {
    val expected = templateSnapshot(entries = listOf(templateEntry(customDish = "Before", updatedAt = 77L)))
    val fresh = templateSnapshot(entries = listOf(templateEntry(customDish = "After", updatedAt = 77L)))
    assertThrows(MenuMutationStaleException::class.java) {
      MenuMutationSnapshotGuard.requireTemplateAggregateUnchanged(expected, fresh)
    }
  }

  @Test
  fun template_childUpdatedAtChanged_detected() {
    val expected = templateSnapshot(entries = listOf(templateEntry(customDish = "Same", updatedAt = 50L)))
    val fresh = templateSnapshot(entries = listOf(templateEntry(customDish = "Same", updatedAt = 99L)))
    assertThrows(MenuMutationStaleException::class.java) {
      MenuMutationSnapshotGuard.requireTemplateAggregateUnchanged(expected, fresh)
    }
  }

  @Test
  fun template_parentPayloadDriftSameUpdatedAt_detected() {
    val expected = templateSnapshot(
      parent = templateParent(updatedAt = 200L, name = "Before"),
      entries = emptyList(),
    )
    val fresh = templateSnapshot(
      parent = templateParent(updatedAt = 200L, name = "After"),
      entries = emptyList(),
    )
    assertThrows(MenuMutationStaleException::class.java) {
      MenuMutationSnapshotGuard.requireTemplateAggregateUnchanged(expected, fresh)
    }
  }

  private fun weeklySnapshot(
    parent: WeeklyMenuEntity = parent(updatedAt = 10L),
    entries: List<MenuEntryEntity>,
  ) = WeeklyMenuWithEntries(menu = parent, entries = entries)

  private fun templateSnapshot(
    parent: MenuTemplateEntity = templateParent(updatedAt = 10L),
    entries: List<MenuTemplateEntryEntity>,
  ) = MenuTemplateWithEntries(template = parent, entries = entries)

  private fun parent(
    updatedAt: Long = 0L,
    isAutoGenerated: Boolean = false,
  ) = WeeklyMenuEntity(
    id = canonicalParentId,
    startDateMillis = weekStart,
    isAutoGenerated = isAutoGenerated,
    createdAt = 1L,
    updatedAt = updatedAt,
  )

  private fun templateParent(
    updatedAt: Long = 0L,
    name: String = "Week",
  ) = MenuTemplateEntity(
    id = templateId,
    name = name,
    createdAt = 1L,
    updatedAt = updatedAt,
  )

  private fun entry(
    day: Int = 0,
    meal: String = "BREAKFAST",
    customDish: String = "Toast",
    updatedAt: Long = 0L,
  ) = MenuEntryEntity(
    id = MenuSyncIds.menuEntryId(weekStart, day, meal),
    menuId = canonicalParentId,
    dayOfWeek = day,
    mealType = meal,
    recipeId = null,
    customDish = customDish,
    servings = 1,
    assignedMemberId = null,
    cookingTaskId = null,
    prepTaskId = null,
    updatedAt = updatedAt,
  )

  private fun templateEntry(
    day: Int = 0,
    meal: String = "BREAKFAST",
    customDish: String = "Toast",
    updatedAt: Long = 0L,
  ) = MenuTemplateEntryEntity(
    id = MenuSyncIds.menuTemplateEntryId(templateId, day, meal),
    templateId = templateId,
    dayOfWeek = day,
    mealType = meal,
    recipeId = null,
    customDish = customDish,
    servings = 1,
    assignedMemberId = null,
    cookingTaskId = null,
    prepTaskId = null,
    updatedAt = updatedAt,
  )
}
