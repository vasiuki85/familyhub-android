    @Test
    fun dailyAssignments_finalIdTieBreak_lowerLexWinsBothOrders() {
        val low = ExportDailyAssignment(
            id = "aaa",
            weekStartMillis = 1L,
            dayOfWeek = 0,
            assignedMemberId = "member",
            rewardPoints = 3,
            isRated = true,
            updatedAt = 5L
        )
        val high = low.copy(id = "bbb")
        assertLowerIdWinsBothOrders(low, high, MenuRecordComparator::compareDailyAssignments)
