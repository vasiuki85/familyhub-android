    @Test
    fun dailyAssignments_nullVsEmptyMemberAndRatedTieBreak() {
        val base = ExportDailyAssignment(
            id = "z",
            weekStartMillis = 1L,
            dayOfWeek = 0,
            updatedAt = 5L
        )
        val withNull = base.copy(id = "n", assignedMemberId = null)
        val withEmpty = base.copy(id = "e", assignedMemberId = "")
        assertTrue(
            MenuRecordComparator.compareDailyAssignments(withEmpty, withNull) > 0
        )

        val rated = base.copy(id = "r", assignedMemberId = "m", isRated = true, rewardPoints = 1)
        val unrated = base.copy(id = "u", assignedMemberId = "m", isRated = false, rewardPoints = 1)
        assertTrue(MenuRecordComparator.compareDailyAssignments(rated, unrated) > 0)

        val highPts = base.copy(id = "h", assignedMemberId = "m", rewardPoints = 9, isRated = false)
        val lowPts = base.copy(id = "l", assignedMemberId = "m", rewardPoints = 1, isRated = false)
        assertTrue(MenuRecordComparator.compareDailyAssignments(highPts, lowPts) > 0)

        assertAntisymmetry(rated, unrated, MenuRecordComparator::compareDailyAssignments)
        assertAssociativity(rated, highPts, lowPts, MenuRecordComparator::compareDailyAssignments)
        // rewardPoints is compared before isRated, so highPts ("h") is the unique max.
        assertPermutationStable(
            listOf(rated, highPts, lowPts),
            MenuRecordComparator::compareDailyAssignments,
            "h"
        )
    }

    private fun <T> assertLowerIdWinsBothOrders(
        lowerId: T,
        higherId: T,
        compare: (T, T) -> Int,
        idOf: (T) -> String = {
            when (it) {
                is ExportWeeklyMenu -> it.id
                is ExportMenuEntry -> it.id
                is ExportMenuTemplate -> it.id
                is ExportMenuTemplateEntry -> it.id
                is ExportDailyAssignment -> it.id
                else -> error("unsupported")
            }
        }
    ) {
        assertTrue(compare(lowerId, higherId) > 0)
        assertTrue(compare(higherId, lowerId) < 0)
        assertEquals(
            idOf(lowerId),
            idOf(MenuRecordComparator.selectWinner(listOf(higherId, lowerId), compare))
        )
        assertEquals(
            idOf(lowerId),
            idOf(MenuRecordComparator.selectWinner(listOf(lowerId, higherId), compare))
        )
    }

    private fun <T> assertAntisymmetry(a: T, b: T, compare: (T, T) -> Int) {
        assertEquals(0, compare(a, a))
        assertEquals(-compare(a, b), compare(b, a))
    }

    private fun <T> assertAssociativity(a: T, b: T, c: T, compare: (T, T) -> Int) {
        val left = MenuRecordComparator.selectWinner(
            listOf(MenuRecordComparator.selectWinner(listOf(a, b), compare), c),
            compare
        )
        val right = MenuRecordComparator.selectWinner(
            listOf(a, MenuRecordComparator.selectWinner(listOf(b, c), compare)),
            compare
        )
        assertEquals(left, right)
    }

    private fun <T> assertPermutationStable(
        items: List<T>,
        compare: (T, T) -> Int,
        expectedId: String,
        idOf: (T) -> String = {
            when (it) {
                is ExportWeeklyMenu -> it.id
                is ExportMenuEntry -> it.id
                is ExportMenuTemplate -> it.id
                is ExportMenuTemplateEntry -> it.id
                is ExportDailyAssignment -> it.id
                else -> error("unsupported")
            }
        }
    ) {
        val perms = permute(items)
        val winners = perms.map { MenuRecordComparator.selectWinner(it, compare) }
        assertTrue(winners.all { idOf(it) == expectedId })
    }

    private fun <T> permute(items: List<T>): List<List<T>> {
        if (items.size <= 1) return listOf(items)
        val result = mutableListOf<List<T>>()
        items.forEachIndexed { index, item ->
            val rest = items.filterIndexed { i, _ -> i != index }
            permute(rest).forEach { tail -> result += listOf(item) + tail }
        }
        return result
    }
}
