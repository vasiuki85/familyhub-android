package com.familyhub.data.menu

import com.familyhub.data.export.ExportDailyAssignment
import com.familyhub.data.export.ExportMenuEntry
import com.familyhub.data.export.ExportMenuTemplate
import com.familyhub.data.export.ExportMenuTemplateEntry
import com.familyhub.data.export.ExportWeeklyMenu
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

class MenuRecordComparatorTest {

    @Test
    fun weeklyMenus_antisymmetryAndAssociativityAndPermutations() {
        val a = ExportWeeklyMenu(
            id = "a",
            startDateMillis = 1L,
            isAutoGenerated = false,
            createdAt = 10L,
            updatedAt = 10L
        )
        val b = ExportWeeklyMenu(
            id = "b",
            startDateMillis = 1L,
            isAutoGenerated = true,
            createdAt = 10L,
            updatedAt = 10L
        )
        val c = ExportWeeklyMenu(
            id = "c",
            startDateMillis = 1L,
            isAutoGenerated = true,
            createdAt = 9L,
            updatedAt = 10L
        )
        assertAntisymmetry(a, b, MenuRecordComparator::compareWeeklyMenus)
        assertAssociativity(a, b, c, MenuRecordComparator::compareWeeklyMenus)
        assertPermutationStable(listOf(a, b, c), MenuRecordComparator::compareWeeklyMenus, "a")
    }

    @Test
    fun menuEntries_nullVsEmptyAndTypedTieBreaks() {
        val base = ExportMenuEntry(
            id = "z",
            menuId = "m",
            dayOfWeek = 0,
            mealType = "BREAKFAST",
            servings = 1,
            updatedAt = 5L
        )
        val withNullRecipe = base.copy(id = "n", recipeId = null, customDish = null)
        val withEmptyRecipe = base.copy(id = "e", recipeId = "", customDish = null)
        assertTrue(
            MenuRecordComparator.compareMenuEntries(withEmptyRecipe, withNullRecipe) > 0
        )

        val highPrep = base.copy(id = "p1", prepTaskId = "zzz")
        val lowPrep = base.copy(id = "p2", prepTaskId = "aaa")
        assertTrue(MenuRecordComparator.compareMenuEntries(highPrep, lowPrep) > 0)

        val highCook = base.copy(id = "c1", cookingTaskId = "zzz", prepTaskId = null)
        val lowCook = base.copy(id = "c2", cookingTaskId = "aaa", prepTaskId = null)
        assertTrue(MenuRecordComparator.compareMenuEntries(highCook, lowCook) > 0)

        val a = base.copy(id = "a", servings = 3, recipeId = "r")
        val b = base.copy(id = "b", servings = 2, recipeId = "r")
        val c = base.copy(id = "c", servings = 2, recipeId = "q")
        assertAntisymmetry(a, b, MenuRecordComparator::compareMenuEntries)
        assertAssociativity(a, b, c, MenuRecordComparator::compareMenuEntries)
        assertPermutationStable(listOf(a, b, c), MenuRecordComparator::compareMenuEntries, "a")
    }

    @Test
    fun menuTemplates_nameAndIdTieBreaks() {
        val a = ExportMenuTemplate(id = "a", name = "Z", createdAt = 1L, updatedAt = 5L)
        val b = ExportMenuTemplate(id = "b", name = "A", createdAt = 9L, updatedAt = 5L)
        val c = ExportMenuTemplate(id = "c", name = "A", createdAt = 1L, updatedAt = 5L)
        assertTrue(MenuRecordComparator.compareMenuTemplates(a, b) > 0)
        assertAntisymmetry(a, b, MenuRecordComparator::compareMenuTemplates)
        assertAssociativity(a, b, c, MenuRecordComparator::compareMenuTemplates)
        assertPermutationStable(listOf(a, b, c), MenuRecordComparator::compareMenuTemplates, "a")
    }

    @Test
    fun templateEntries_nullVsEmptyAndIgnoreTaskRefs() {
        val base = ExportMenuTemplateEntry(
            id = "z",
            templateId = "t",
            dayOfWeek = 0,
            mealType = "LUNCH",
            servings = 1,
            updatedAt = 5L
        )
        val withNull = base.copy(id = "n", customDish = null)
        val withEmpty = base.copy(id = "e", customDish = "")
        assertTrue(MenuRecordComparator.compareTemplateEntries(withEmpty, withNull) > 0)

        val taskRefsA = base.copy(
            id = "same",
            cookingTaskId = "cook-a",
            prepTaskId = "prep-a"
        )
        val taskRefsB = base.copy(
            id = "same",
            cookingTaskId = "cook-b",
            prepTaskId = "prep-b"
        )
        assertEquals(0, MenuRecordComparator.compareTemplateEntries(taskRefsA, taskRefsB))

        val a = base.copy(id = "a", servings = 5, assignedMemberId = "m")
        val b = base.copy(id = "b", servings = 1, assignedMemberId = "m")
        val c = base.copy(id = "c", servings = 1, assignedMemberId = null)
        assertAntisymmetry(a, b, MenuRecordComparator::compareTemplateEntries)
        assertAssociativity(a, b, c, MenuRecordComparator::compareTemplateEntries)
        assertPermutationStable(listOf(a, b, c), MenuRecordComparator::compareTemplateEntries, "a")
    }

    @Test
    fun weeklyMenus_finalIdTieBreak_lowerLexWinsBothOrders() {
        assertLowerIdWinsBothOrders(
            ExportWeeklyMenu(
                id = "aaa",
                startDateMillis = 1L,
                isAutoGenerated = false,
                createdAt = 10L,
                updatedAt = 10L
            ),
            ExportWeeklyMenu(
                id = "bbb",
                startDateMillis = 1L,
                isAutoGenerated = false,
                createdAt = 10L,
                updatedAt = 10L
            ),
            MenuRecordComparator::compareWeeklyMenus
        )
    }

    @Test
    fun menuEntries_finalIdTieBreak_lowerLexWinsBothOrders() {
        val low = ExportMenuEntry(
            id = "aaa",
            menuId = "m",
            dayOfWeek = 0,
            mealType = "BREAKFAST",
            recipeId = "r",
            customDish = "dish",
            servings = 2,
            assignedMemberId = "member",
            cookingTaskId = "cook",
            prepTaskId = "prep",
            updatedAt = 5L
        )
        val high = low.copy(id = "bbb")
        assertLowerIdWinsBothOrders(low, high, MenuRecordComparator::compareMenuEntries)
    }

    @Test
    fun menuTemplates_finalIdTieBreak_lowerLexWinsBothOrders() {
        assertLowerIdWinsBothOrders(
            ExportMenuTemplate(id = "aaa", name = "Week", createdAt = 10L, updatedAt = 5L),
            ExportMenuTemplate(id = "bbb", name = "Week", createdAt = 10L, updatedAt = 5L),
