package com.familyhub.ui.screens.food

import com.familyhub.domain.model.MealType
import com.familyhub.domain.model.MenuEntry
import com.familyhub.domain.model.Recipe
import com.familyhub.domain.model.RecipeCategory
import com.familyhub.domain.model.RecipeDifficulty
import com.familyhub.domain.model.WeeklyMenu
import com.familyhub.domain.utils.WeekUtils
import java.util.Calendar
import org.junit.Assert.assertEquals
import org.junit.Test

class FoodHubUiMapperTest {

    @Test
    fun map_showsOnlyTodayMealsAndResolvesRecipeTitles() {
        val monday = Calendar.getInstance().apply {
            set(2026, Calendar.JULY, 27, 12, 0, 0)
            set(Calendar.MILLISECOND, 0)
        }.timeInMillis
        val weekStart = WeekUtils.getWeekStartMillis(monday)
        val recipe = recipe("recipe", "Сырники", updatedAt = 10L)
        val menu = WeeklyMenu(
            id = "menu",
            startDateMillis = weekStart,
            isAutoGenerated = false,
            entries = listOf(
                entry("breakfast", day = 0, recipeId = recipe.id),
                entry("lunch", day = 0, customDish = "Овощной суп"),
                entry("tomorrow", day = 1, customDish = "Паста"),
            ),
            createdAt = 1L,
            updatedAt = 1L,
        )

        val result = FoodHubUiMapper.map(menu, listOf(recipe), monday)

        assertEquals(
            listOf("Сырники", "Овощной суп"),
            result.todayMeals.map { it.title },
        )
    }

    @Test
    fun map_prioritizesFavoritesThenRecentRecipes() {
        val now = System.currentTimeMillis()
        val result = FoodHubUiMapper.map(
            menu = null,
            recipes = listOf(
                recipe("old", "Старый", updatedAt = 1L),
                recipe("new", "Новый", updatedAt = 20L),
                recipe("favorite", "Любимый", updatedAt = 2L, isFavorite = true),
                recipe("fourth", "Четвёртый", updatedAt = 0L),
            ),
            nowMillis = now,
        )

        assertEquals(
            listOf("Любимый", "Новый", "Старый"),
            result.recipePreviews.map { it.title },
        )
    }

    private fun entry(
        id: String,
        day: Int,
        recipeId: String? = null,
        customDish: String? = null,
    ) = MenuEntry(
        id = id,
        menuId = "menu",
        dayOfWeek = day,
        mealType = if (id == "breakfast") MealType.BREAKFAST else MealType.LUNCH,
        recipeId = recipeId,
        customDish = customDish,
        servings = 2,
        assignedMemberId = null,
        cookingTaskId = null,
        prepTaskId = null,
    )

    private fun recipe(
        id: String,
        title: String,
        updatedAt: Long,
        isFavorite: Boolean = false,
    ) = Recipe(
        id = id,
        title = title,
        description = "",
        servings = 2,
        prepTimeMinutes = 20,
        difficulty = RecipeDifficulty.EASY,
        isFavorite = isFavorite,
        imageUrl = null,
        notes = "",
        tags = emptyList(),
        ingredients = emptyList(),
        steps = emptyList(),
        category = RecipeCategory.APPETIZER,
        createdAt = 1L,
        updatedAt = updatedAt,
    )
}
