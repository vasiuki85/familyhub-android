package com.familyhub.ui.screens.menu

import com.familyhub.domain.model.MealType
import com.familyhub.domain.model.MenuEntry
import com.familyhub.domain.model.Recipe
import com.familyhub.domain.model.RecipeCategory
import com.familyhub.domain.model.WeeklyMenu
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

class MenuPrepTaskPlannerTest {

    @Test
    fun plan_collectsPrepTaskDeletesWithoutMutatingOtherEntries() {
        val menu = weeklyMenu(
            entries = listOf(
                entry(recipeId = "short", prepTaskId = "prep-short"),
                entry(recipeId = "long", prepTaskId = "prep-long"),
                entry(recipeId = null, prepTaskId = "prep-custom"),
            ),
        )
        val recipes = mapOf(
            "short" to recipe(id = "short", prepTimeMinutes = 30),
            "long" to recipe(id = "long", prepTimeMinutes = 120),
        )

        val plan = MenuPrepTaskPlanner.plan(menu, recipes, LONG_PREP_THRESHOLD)

        assertEquals(setOf("prep-short", "prep-custom"), plan.taskIdsToDeleteAfterCommit)
        assertEquals(null, plan.menu.entries[0].prepTaskId)
        assertEquals("prep-long", plan.menu.entries[1].prepTaskId)
        assertEquals(null, plan.menu.entries[2].prepTaskId)
    }

    @Test
    fun plan_withNoDeletes_returnsEmptyDeleteSet() {
        val menu = weeklyMenu(entries = listOf(entry(recipeId = "long", prepTaskId = "prep-long")))
        val recipes = mapOf("long" to recipe(id = "long", prepTimeMinutes = 120))

        val plan = MenuPrepTaskPlanner.plan(menu, recipes, LONG_PREP_THRESHOLD)

        assertTrue(plan.taskIdsToDeleteAfterCommit.isEmpty())
        assertEquals("prep-long", plan.menu.entries.single().prepTaskId)
    }

    private fun weeklyMenu(entries: List<MenuEntry>) = WeeklyMenu(
        id = "menu-1",
        startDateMillis = WEEK_START,
        isAutoGenerated = false,
        createdAt = 1L,
        entries = entries,
    )

    private fun entry(recipeId: String?, prepTaskId: String?) = MenuEntry(
        id = "entry-1",
        menuId = "menu-1",
        dayOfWeek = 0,
        mealType = MealType.BREAKFAST,
        recipeId = recipeId,
        customDish = null,
        servings = 4,
        assignedMemberId = null,
        cookingTaskId = null,
        prepTaskId = prepTaskId,
    )

    private fun recipe(id: String, prepTimeMinutes: Int) = Recipe(
        id = id,
        title = "Recipe",
        description = "",
        servings = 4,
        prepTimeMinutes = prepTimeMinutes,
        difficulty = com.familyhub.domain.model.RecipeDifficulty.EASY,
        isFavorite = false,
        imageUrl = null,
        notes = "",
        tags = emptyList(),
        ingredients = emptyList(),
        steps = emptyList(),
        category = RecipeCategory.FIRST,
        createdAt = 1L,
        updatedAt = 1L,
    )

    private companion object {
        const val WEEK_START = 1_700_000_000_000L
        const val LONG_PREP_THRESHOLD = 90
    }
}
