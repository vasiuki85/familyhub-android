package com.familyhub.domain.model

/**
 * Роль члена семьи в системе
 */
enum class MemberRole {
    ADMIN,   // Администратор - создатель семьи, полный доступ + управление участниками
    PARENT,  // Родитель - имеет полный доступ к функциям, но не может удалять участников (кроме себя)
    CHILD,   // Ребёнок - имеет ограниченный доступ
    PENDING  // Ожидает подтверждения
}

