package com.familyhub.data.local.db.migration

import com.familyhub.data.export.ExportDailyAssignment
import com.familyhub.data.export.ExportData
import com.familyhub.data.export.ExportMenuEntry
import com.familyhub.data.export.ExportMenuTemplate
import com.familyhub.data.export.ExportMenuTemplateEntry
import com.familyhub.data.export.ExportWeeklyMenu
import com.familyhub.data.menu.MenuSnapshotCanonicalizer

/**
 * Legacy v36 row shapes (no updatedAt) for migration planning.
 * Planner never reads v37 entities.
 */
data class LegacyWeeklyMenuRow(
    val id: String,
    val startDateMillis: Long,
    val isAutoGenerated: Boolean,
    val createdAt: Long
)

data class LegacyMenuEntryRow(
    val id: String,
    val menuId: String,
    val dayOfWeek: Int,
    val mealType: String,
    val recipeId: String?,
    val customDish: String?,
    val servings: Int,
    val assignedMemberId: String?,
    val cookingTaskId: String?,
    val prepTaskId: String?
)

data class LegacyMenuTemplateRow(
    val id: String,
    val name: String,
    val createdAt: Long
)

data class LegacyMenuTemplateEntryRow(
    val id: String,
    val templateId: String,
    val dayOfWeek: Int,
    val mealType: String,
    val recipeId: String?,
    val customDish: String?,
    val servings: Int,
    val assignedMemberId: String?,
    val cookingTaskId: String?,
    val prepTaskId: String?
)

data class LegacyDailyAssignmentRow(
    val id: String,
    val weekStartMillis: Long,
    val dayOfWeek: Int,
    val assignedMemberId: String?,
    val rewardPoints: Int?,
    val isRated: Boolean
)

data class LegacyMenuSnapshotV36(
    val weeklyMenus: List<LegacyWeeklyMenuRow> = emptyList(),
    val menuEntries: List<LegacyMenuEntryRow> = emptyList(),
    val menuTemplates: List<LegacyMenuTemplateRow> = emptyList(),
    val menuTemplateEntries: List<LegacyMenuTemplateEntryRow> = emptyList(),
    val dailyAssignments: List<LegacyDailyAssignmentRow> = emptyList()
)

data class PlannedWeeklyMenuV37(
    val id: String,
    val startDateMillis: Long,
    val isAutoGenerated: Boolean,
    val createdAt: Long,
    val updatedAt: Long
)

data class PlannedMenuEntryV37(
    val id: String,
    val menuId: String,
    val dayOfWeek: Int,
    val mealType: String,
    val recipeId: String?,
    val customDish: String?,
    val servings: Int,
    val assignedMemberId: String?,
    val cookingTaskId: String?,
    val prepTaskId: String?,
    val updatedAt: Long
)

data class PlannedMenuTemplateV37(
    val id: String,
    val name: String,
    val createdAt: Long,
    val updatedAt: Long
)

data class PlannedMenuTemplateEntryV37(
    val id: String,
    val templateId: String,
    val dayOfWeek: Int,
    val mealType: String,
    val recipeId: String?,
    val customDish: String?,
    val servings: Int,
    val assignedMemberId: String?,
    val cookingTaskId: String?,
    val prepTaskId: String?,
    val updatedAt: Long
)

data class PlannedDailyAssignmentV37(
    val id: String,
    val weekStartMillis: Long,
    val dayOfWeek: Int,
    val assignedMemberId: String?,
    val rewardPoints: Int?,
    val isRated: Boolean,
    val updatedAt: Long
)

data class PlannedMenuV37(
    val weeklyMenus: List<PlannedWeeklyMenuV37>,
    val menuEntries: List<PlannedMenuEntryV37>,
    val menuTemplates: List<PlannedMenuTemplateV37>,
    val menuTemplateEntries: List<PlannedMenuTemplateEntryV37>,
    val dailyAssignments: List<PlannedDailyAssignmentV37>
)

/**
 * Pure planner: legacy v36 DTOs → planned v37 rows via [MenuSnapshotCanonicalizer].
 */
object Migration36To37Planner {

    fun plan(legacy: LegacyMenuSnapshotV36): PlannedMenuV37 {
        val export = ExportData(
            weeklyMenus = legacy.weeklyMenus.map {
                ExportWeeklyMenu(
                    id = it.id,
                    startDateMillis = it.startDateMillis,
                    isAutoGenerated = it.isAutoGenerated,
                    createdAt = it.createdAt,
                    updatedAt = 0L
                )
            },
            menuEntries = legacy.menuEntries.map {
                ExportMenuEntry(
                    id = it.id,
                    menuId = it.menuId,
                    dayOfWeek = it.dayOfWeek,
                    mealType = it.mealType,
                    recipeId = it.recipeId,
                    customDish = it.customDish,
                    servings = it.servings,
                    assignedMemberId = it.assignedMemberId,
                    cookingTaskId = it.cookingTaskId,
                    prepTaskId = it.prepTaskId,
                    updatedAt = 0L
                )
            },
            menuTemplates = legacy.menuTemplates.map {
                ExportMenuTemplate(
                    id = it.id,
                    name = it.name,
                    createdAt = it.createdAt,
                    updatedAt = 0L
                )
            },
            menuTemplateEntries = legacy.menuTemplateEntries.map {
                ExportMenuTemplateEntry(
                    id = it.id,
                    templateId = it.templateId,
                    dayOfWeek = it.dayOfWeek,
                    mealType = it.mealType,
                    recipeId = it.recipeId,
                    customDish = it.customDish,
                    servings = it.servings,
                    assignedMemberId = it.assignedMemberId,
                    cookingTaskId = it.cookingTaskId,
                    prepTaskId = it.prepTaskId,
                    updatedAt = 0L
                )
            },
            dailyAssignments = legacy.dailyAssignments.map {
                ExportDailyAssignment(
                    id = it.id,
                    weekStartMillis = it.weekStartMillis,
                    dayOfWeek = it.dayOfWeek,
                    assignedMemberId = it.assignedMemberId,
                    rewardPoints = it.rewardPoints,
                    isRated = it.isRated,
                    updatedAt = 0L
                )
            }
        )
        val canonical = MenuSnapshotCanonicalizer.canonicalize(export)
        return PlannedMenuV37(
            weeklyMenus = canonical.weeklyMenus.map {
                PlannedWeeklyMenuV37(
                    id = it.id,
                    startDateMillis = it.startDateMillis,
                    isAutoGenerated = it.isAutoGenerated,
                    createdAt = it.createdAt,
                    updatedAt = it.updatedAt
                )
            },
            menuEntries = canonical.menuEntries.map {
                PlannedMenuEntryV37(
                    id = it.id,
                    menuId = it.menuId,
                    dayOfWeek = it.dayOfWeek,
                    mealType = it.mealType,
                    recipeId = it.recipeId,
                    customDish = it.customDish,
                    servings = it.servings,
                    assignedMemberId = it.assignedMemberId,
                    cookingTaskId = it.cookingTaskId,
                    prepTaskId = it.prepTaskId,
                    updatedAt = it.updatedAt
                )
            },
            menuTemplates = canonical.menuTemplates.map {
                PlannedMenuTemplateV37(
                    id = it.id,
                    name = it.name,
                    createdAt = it.createdAt,
                    updatedAt = it.updatedAt
                )
            },
            menuTemplateEntries = canonical.menuTemplateEntries.map {
                PlannedMenuTemplateEntryV37(
                    id = it.id,
                    templateId = it.templateId,
                    dayOfWeek = it.dayOfWeek,
                    mealType = it.mealType,
                    recipeId = it.recipeId,
                    customDish = it.customDish,
                    servings = it.servings,
                    assignedMemberId = it.assignedMemberId,
                    cookingTaskId = null,
                    prepTaskId = null,
                    updatedAt = it.updatedAt
                )
            },
            dailyAssignments = canonical.dailyAssignments.map {
                PlannedDailyAssignmentV37(
                    id = it.id,
                    weekStartMillis = it.weekStartMillis,
                    dayOfWeek = it.dayOfWeek,
                    assignedMemberId = it.assignedMemberId,
                    rewardPoints = it.rewardPoints,
                    isRated = it.isRated,
                    updatedAt = it.updatedAt
                )
            }
        )
    }
}
