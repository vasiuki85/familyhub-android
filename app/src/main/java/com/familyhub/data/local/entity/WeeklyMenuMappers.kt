package com.familyhub.data.local.entity

import androidx.room.Embedded
import androidx.room.Relation
import com.familyhub.domain.model.MealType
import com.familyhub.domain.model.MenuEntry
import com.familyhub.domain.model.WeeklyMenu

data class WeeklyMenuWithEntries(
    @Embedded val menu: WeeklyMenuEntity,
    @Relation(
        parentColumn = "id",
        entityColumn = "menuId"
    )
    val entries: List<MenuEntryEntity>
)

fun WeeklyMenuWithEntries.toDomain(): WeeklyMenu = WeeklyMenu(
    id = menu.id,
    startDateMillis = menu.startDateMillis,
    isAutoGenerated = menu.isAutoGenerated,
    createdAt = menu.createdAt,
    updatedAt = menu.updatedAt,
    entries = entries.map { entity ->
        MenuEntry(
            id = entity.id,
            menuId = entity.menuId,
            dayOfWeek = entity.dayOfWeek,
            mealType = MealType.valueOf(entity.mealType),
            recipeId = entity.recipeId,
            customDish = entity.customDish,
            servings = entity.servings,
            assignedMemberId = entity.assignedMemberId,
            cookingTaskId = entity.cookingTaskId,
            prepTaskId = entity.prepTaskId,
            updatedAt = entity.updatedAt
        )
    }
)

data class WeeklyMenuEntities(
    val menu: WeeklyMenuEntity,
    val entries: List<MenuEntryEntity>
)

fun WeeklyMenu.toEntities(): WeeklyMenuEntities = WeeklyMenuEntities(
    menu = WeeklyMenuEntity(
        id = id,
        startDateMillis = startDateMillis,
        isAutoGenerated = isAutoGenerated,
        createdAt = createdAt,
        updatedAt = updatedAt
    ),
    entries = entries.map { entry ->
        MenuEntryEntity(
            id = entry.id,
            menuId = entry.menuId,
            dayOfWeek = entry.dayOfWeek,
            mealType = entry.mealType.name,
            recipeId = entry.recipeId,
            customDish = entry.customDish,
            servings = entry.servings,
            assignedMemberId = entry.assignedMemberId,
            cookingTaskId = entry.cookingTaskId,
            prepTaskId = entry.prepTaskId,
            updatedAt = entry.updatedAt
        )
    }
)
