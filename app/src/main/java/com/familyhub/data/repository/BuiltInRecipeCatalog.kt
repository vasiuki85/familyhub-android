    private fun recipe(
        number: Int,
        title: String,
        description: String,
        time: Int,
        difficulty: RecipeDifficulty,
        category: RecipeCategory,
        tags: List<String>,
        ingredients: List<Pair<String, String>>,
        steps: List<String>,
    ): Recipe {
        val suffix = number.toString().padStart(2, '0')
        val recipeId = "builtin-recipe-$CATALOG_VERSION-$suffix"
        return Recipe(
            id = recipeId,
            title = title,
            description = description,
            servings = 4,
            prepTimeMinutes = time,
            difficulty = difficulty,
            isFavorite = false,
            imageUrl = BuiltInRecipeImage.tokens[number - 1],
            notes = "",
            tags = tags,
            ingredients = ingredients.mapIndexed { index, ingredient ->
                RecipeIngredient(
                    id = "$recipeId-ingredient-${(index + 1).toString().padStart(2, '0')}",
                    recipeId = recipeId,
                    name = ingredient.first,
                    quantity = ingredient.second,
                )
            },
            steps = steps.mapIndexed { index, descriptionText ->
                RecipeStep(
                    id = "$recipeId-step-${(index + 1).toString().padStart(2, '0')}",
                    recipeId = recipeId,
                    order = index,
                    description = descriptionText,
                )
            },
            category = category,
            createdAt = CREATED_AT,
            updatedAt = CREATED_AT,
        )
    }
