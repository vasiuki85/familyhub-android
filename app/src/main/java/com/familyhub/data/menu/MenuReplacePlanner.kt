data class WeeklyMenuReplacePlan(
    val canonicalParentId: String,
    val legacyParentId: String?,
    val parentEntity: WeeklyMenuEntity,
    val parentPayloadChanged: Boolean,
    val changedEntries: List<MenuEntryEntity>,
    val unchangedEntries: List<MenuEntryEntity>,
    val removedEntries: List<MenuEntryEntity>,
    val changedSources: List<MenuEntryEntity>,
) {
    fun hasMutations(current: WeeklyMenuWithEntries?): Boolean {
        if (current == null) return true
        if (changedEntries.isNotEmpty() || removedEntries.isNotEmpty()) return true
        if (parentPayloadChanged || legacyParentId != null) return true
        if (current.menu != parentEntity.copy(updatedAt = current.menu.updatedAt)) return true
        return unchangedEntries.any { planned ->
            val existing = current.entries.find {
                it.dayOfWeek == planned.dayOfWeek && it.mealType == planned.mealType
            } ?: return true
            existing != planned
        }
    }
}

data class MenuTemplateReplacePlan(
    val templateEntity: MenuTemplateEntity,
    val parentPayloadChanged: Boolean,
    val changedEntries: List<MenuTemplateEntryEntity>,
    val unchangedEntries: List<MenuTemplateEntryEntity>,
    val removedEntries: List<MenuTemplateEntryEntity>,
    val changedSources: List<MenuTemplateEntryEntity>,
) {
    fun hasMutations(current: MenuTemplateWithEntries?): Boolean {
        if (current == null) return true
        if (changedEntries.isNotEmpty() || removedEntries.isNotEmpty()) return true
        if (parentPayloadChanged) return true
        if (current.template != templateEntity.copy(updatedAt = current.template.updatedAt)) return true
        return unchangedEntries.any { planned ->
            val existing = current.entries.find {
                it.dayOfWeek == planned.dayOfWeek && it.mealType == planned.mealType
            } ?: return true
            existing != planned
        }
    }
}

object MenuReplacePlanner {

    fun planWeeklyReplace(
        current: WeeklyMenuWithEntries?,
        desired: WeeklyMenu,
    ): WeeklyMenuReplacePlan {
        val canonicalParentId = MenuSyncIds.weeklyMenuId(desired.startDateMillis)
        val createdAt = current?.menu?.createdAt ?: desired.createdAt
        val parentEntity = WeeklyMenuEntity(
            id = canonicalParentId,
            startDateMillis = desired.startDateMillis,
            isAutoGenerated = desired.isAutoGenerated,
            createdAt = createdAt,
            updatedAt = current?.menu?.updatedAt ?: desired.updatedAt,
        )
        val parentPayloadChanged = current?.menu?.let { existing ->
            !MenuPayloadComparator.weeklyParentPayloadEqual(existing, parentEntity)
        } ?: true

        val currentBySlot = current?.entries.orEmpty().associateBy { entrySlotKey(it) }
        val desiredBySlot = desired.entries.associateBy { entrySlotKey(it) }

        val changedEntries = mutableListOf<MenuEntryEntity>()
        val unchangedEntries = mutableListOf<MenuEntryEntity>()
        val changedSources = mutableListOf<MenuEntryEntity>()

        for ((slot, desiredEntry) in desiredBySlot) {
            val normalized = normalizeWeeklyEntry(desiredEntry, canonicalParentId, desired.startDateMillis)
            val existing = currentBySlot[slot]
            if (existing != null && MenuPayloadComparator.weeklyEntryPayloadEqual(existing, normalized)) {
                unchangedEntries += existing.copy(
                    id = normalized.id,
                    menuId = canonicalParentId,
                    updatedAt = existing.updatedAt,
                )
            } else {
                changedEntries += normalized
                if (existing != null) {
                    changedSources += existing
                }
            }
        }

        val removedEntries = current?.entries.orEmpty().filter { entry ->
            entrySlotKey(entry) !in desiredBySlot
        }

        val legacyParentId = current?.menu?.id?.takeIf { it != canonicalParentId }

        return WeeklyMenuReplacePlan(
            canonicalParentId = canonicalParentId,
            legacyParentId = legacyParentId,
            parentEntity = parentEntity,
            parentPayloadChanged = parentPayloadChanged,
            changedEntries = changedEntries,
            unchangedEntries = unchangedEntries,
            removedEntries = removedEntries,
            changedSources = changedSources,
        )
    }

    fun planTemplateReplace(
        current: MenuTemplateWithEntries?,
        desired: MenuTemplate,
    ): MenuTemplateReplacePlan {
        val templateId = desired.id
        val parentEntity = MenuTemplateEntity(
            id = templateId,
            name = desired.name,
            createdAt = current?.template?.createdAt ?: desired.createdAt,
            updatedAt = current?.template?.updatedAt ?: desired.updatedAt,
        )
        val parentPayloadChanged = current?.template?.let { existing ->
            !MenuPayloadComparator.templateParentPayloadEqual(existing, parentEntity)
        } ?: true

        val currentBySlot = current?.entries.orEmpty().associateBy { entrySlotKey(it) }
        val desiredBySlot = desired.entries.associateBy { entrySlotKey(it) }

        val changedEntries = mutableListOf<MenuTemplateEntryEntity>()
        val unchangedEntries = mutableListOf<MenuTemplateEntryEntity>()
        val changedSources = mutableListOf<MenuTemplateEntryEntity>()

        for ((slot, desiredEntry) in desiredBySlot) {
            val normalized = normalizeTemplateEntry(desiredEntry, templateId)
            val existing = currentBySlot[slot]
            if (existing != null && MenuPayloadComparator.templateEntryPayloadEqual(existing, normalized)) {
                if (existing.cookingTaskId != null || existing.prepTaskId != null) {
                    changedEntries += normalized
                    changedSources += existing
                } else {
                    unchangedEntries += existing.copy(
                        id = normalized.id,
                        templateId = templateId,
                        updatedAt = existing.updatedAt,
                    )
                }
            } else {
                changedEntries += normalized
                if (existing != null) {
                    changedSources += existing
                }
            }
        }

        val removedEntries = current?.entries.orEmpty().filter { entry ->
            entrySlotKey(entry) !in desiredBySlot
        }

        return MenuTemplateReplacePlan(
            templateEntity = parentEntity,
            parentPayloadChanged = parentPayloadChanged,
            changedEntries = changedEntries,
            unchangedEntries = unchangedEntries,
            removedEntries = removedEntries,
            changedSources = changedSources,
        )
    }

    fun maxMutationUpdatedAt(
        parentUpdatedAt: Long,
        cohortUpdatedAts: Iterable<Long>,
    ): Long {
        var max = parentUpdatedAt
        for (updatedAt in cohortUpdatedAts) {
            max = maxOf(max, updatedAt)
        }
        return max
    }

    private fun normalizeWeeklyEntry(
        entry: MenuEntry,
        parentId: String,
        startDateMillis: Long,
    ): MenuEntryEntity = MenuEntryEntity(
        id = MenuSyncIds.menuEntryId(startDateMillis, entry.dayOfWeek, entry.mealType.name),
        menuId = parentId,
        dayOfWeek = entry.dayOfWeek,
        mealType = entry.mealType.name,
        recipeId = entry.recipeId,
        customDish = entry.customDish,
        servings = entry.servings,
        assignedMemberId = entry.assignedMemberId,
        cookingTaskId = entry.cookingTaskId,
        prepTaskId = entry.prepTaskId,
        updatedAt = 0L,
    )

    private fun normalizeTemplateEntry(
        entry: MenuEntry,
        templateId: String,
    ): MenuTemplateEntryEntity = MenuTemplateEntryEntity(
        id = MenuSyncIds.menuTemplateEntryId(templateId, entry.dayOfWeek, entry.mealType.name),
        templateId = templateId,
        dayOfWeek = entry.dayOfWeek,
        mealType = entry.mealType.name,
        recipeId = entry.recipeId,
        customDish = entry.customDish,
        servings = entry.servings,
        assignedMemberId = entry.assignedMemberId,
        cookingTaskId = null,
        prepTaskId = null,
        updatedAt = 0L,
    )

    private fun entrySlotKey(entry: MenuEntryEntity): Pair<Int, String> =
        entry.dayOfWeek to entry.mealType

    private fun entrySlotKey(entry: MenuTemplateEntryEntity): Pair<Int, String> =
        entry.dayOfWeek to entry.mealType

    private fun entrySlotKey(entry: MenuEntry): Pair<Int, String> =
        entry.dayOfWeek to entry.mealType.name
}
