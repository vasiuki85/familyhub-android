package com.familyhub.data.menu

import com.familyhub.data.local.entity.MenuEntryEntity
import com.familyhub.data.local.entity.MenuTemplateEntryEntity
import com.familyhub.data.local.entity.MenuTemplateEntity
import com.familyhub.data.local.entity.WeeklyMenuEntity

/**
 * Payload equality for menu replace planning.
 *
 * Comparisons intentionally exclude [WeeklyMenuEntity.updatedAt],
 * [MenuEntryEntity.updatedAt], and entity ids / parent foreign keys.
 */
object MenuPayloadComparator {

    fun weeklyParentPayloadEqual(a: WeeklyMenuEntity, b: WeeklyMenuEntity): Boolean =
        a.startDateMillis == b.startDateMillis &&
            a.isAutoGenerated == b.isAutoGenerated &&
            a.createdAt == b.createdAt

    fun templateParentPayloadEqual(a: MenuTemplateEntity, b: MenuTemplateEntity): Boolean =
        a.name == b.name && a.createdAt == b.createdAt

    fun weeklyEntryPayloadEqual(a: MenuEntryEntity, b: MenuEntryEntity): Boolean =
        a.dayOfWeek == b.dayOfWeek &&
            a.mealType == b.mealType &&
            a.recipeId == b.recipeId &&
            a.customDish == b.customDish &&
            a.servings == b.servings &&
            a.assignedMemberId == b.assignedMemberId &&
            a.cookingTaskId == b.cookingTaskId &&
            a.prepTaskId == b.prepTaskId

    fun templateEntryPayloadEqual(a: MenuTemplateEntryEntity, b: MenuTemplateEntryEntity): Boolean =
        a.dayOfWeek == b.dayOfWeek &&
            a.mealType == b.mealType &&
            a.recipeId == b.recipeId &&
            a.customDish == b.customDish &&
            a.servings == b.servings &&
            a.assignedMemberId == b.assignedMemberId
}
