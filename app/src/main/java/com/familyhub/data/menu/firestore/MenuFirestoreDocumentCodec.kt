package com.familyhub.data.menu.firestore

import com.familyhub.data.datastore.DeletedCloudDocumentCollections
import com.familyhub.data.export.ExportDailyAssignment
import com.familyhub.data.export.ExportMenuEntry
import com.familyhub.data.export.ExportMenuTemplate
import com.familyhub.data.export.ExportMenuTemplateEntry
import com.familyhub.data.export.ExportWeeklyMenu
import com.familyhub.data.menu.cloud.MenuCloudSnapshot
import com.familyhub.domain.utils.MenuSyncIds

/**
 * Strict Firestore wire-format codec for the five menu collections.
 *
 * Pure: no Firebase, Room, or DataStore dependencies.
 */
object MenuFirestoreDocumentCodec {

    private val MEAL_TYPES = setOf("BREAKFAST", "LUNCH", "DINNER", "SNACK")

    private val WEEKLY_MENU_KEYS = setOf(
        "id", "startDateMillis", "isAutoGenerated", "createdAt", "updatedAt",
    )
    private val MENU_ENTRY_KEYS = setOf(
        "id", "menuId", "dayOfWeek", "mealType", "servings", "updatedAt",
        "recipeId", "customDish", "assignedMemberId", "cookingTaskId", "prepTaskId",
    )
    private val MENU_TEMPLATE_KEYS = setOf("id", "name", "createdAt", "updatedAt")
    private val MENU_TEMPLATE_ENTRY_KEYS = setOf(
        "id", "templateId", "dayOfWeek", "mealType", "servings", "updatedAt",
        "recipeId", "customDish", "assignedMemberId", "cookingTaskId", "prepTaskId",
    )
    private val DAILY_ASSIGNMENT_KEYS = setOf(
        "id", "weekStartMillis", "dayOfWeek", "isRated", "updatedAt",
        "assignedMemberId", "rewardPoints",
    )

    fun decodeDocument(raw: MenuFirestoreRawDocument): Any = when (raw.collection) {
        DeletedCloudDocumentCollections.WEEKLY_MENUS -> decodeWeeklyMenu(raw.documentId, raw.fields)
        DeletedCloudDocumentCollections.MENU_ENTRIES -> decodeMenuEntry(raw.documentId, raw.fields)
        DeletedCloudDocumentCollections.MENU_TEMPLATES -> decodeMenuTemplate(raw.documentId, raw.fields)
        DeletedCloudDocumentCollections.MENU_TEMPLATE_ENTRIES ->
            decodeMenuTemplateEntry(raw.documentId, raw.fields)
        DeletedCloudDocumentCollections.DAILY_ASSIGNMENTS ->
            decodeDailyAssignment(raw.documentId, raw.fields)
        else -> throw MenuFirestoreDocumentCodecException("Unknown menu collection: ${raw.collection}")
    }

    fun decodeSnapshot(documents: List<MenuFirestoreRawDocument>): MenuCloudSnapshot {
        val weeklyMenus = mutableListOf<ExportWeeklyMenu>()
        val menuEntries = mutableListOf<ExportMenuEntry>()
        val menuTemplates = mutableListOf<ExportMenuTemplate>()
        val menuTemplateEntries = mutableListOf<ExportMenuTemplateEntry>()
        val dailyAssignments = mutableListOf<ExportDailyAssignment>()
        documents.forEach { raw ->
            when (val decoded = decodeDocument(raw)) {
                is ExportWeeklyMenu -> weeklyMenus += decoded
                is ExportMenuEntry -> menuEntries += decoded
                is ExportMenuTemplate -> menuTemplates += decoded
                is ExportMenuTemplateEntry -> menuTemplateEntries += decoded
                is ExportDailyAssignment -> dailyAssignments += decoded
            }
        }
        return MenuCloudSnapshot(
            weeklyMenus = weeklyMenus,
            menuEntries = menuEntries,
            menuTemplates = menuTemplates,
            menuTemplateEntries = menuTemplateEntries,
            dailyAssignments = dailyAssignments,
        )
    }

    fun encodeWeeklyMenu(menu: ExportWeeklyMenu): Map<String, Any?> {
        validateFirestoreId(menu.id, "weekly_menus id")
        requireNonNegativeLongValue(menu.startDateMillis, "startDateMillis")
        requireNonNegativeLongValue(menu.createdAt, "createdAt")
        requireNonNegativeLongValue(menu.updatedAt, "updatedAt")
        return linkedMapOf(
            "id" to menu.id,
            "startDateMillis" to menu.startDateMillis,
            "isAutoGenerated" to menu.isAutoGenerated,
            "createdAt" to menu.createdAt,
            "updatedAt" to menu.updatedAt,
        )
    }

    fun encodeMenuEntry(entry: ExportMenuEntry): Map<String, Any?> = buildEncodedMap(MENU_ENTRY_KEYS) {
        validateFirestoreId(entry.id, "menu_entries id")
        validateReferenceId(entry.menuId, "menuId")
        val dayOfWeek = validateDayOfWeekValue(entry.dayOfWeek, "dayOfWeek")
        val mealType = validateMealTypeValue(entry.mealType, "mealType")
        validateServingsValue(entry.servings, "servings")
        requireNonNegativeLongValue(entry.updatedAt, "updatedAt")
        entry.recipeId?.let { validateReferenceId(it, "recipeId") }
        entry.assignedMemberId?.let { validateReferenceId(it, "assignedMemberId") }
        entry.cookingTaskId?.let { validateReferenceId(it, "cookingTaskId") }
        entry.prepTaskId?.let { validateReferenceId(it, "prepTaskId") }
        put("id", entry.id)
        put("menuId", entry.menuId)
        put("dayOfWeek", dayOfWeek)
        put("mealType", mealType)
        put("servings", entry.servings)
        put("updatedAt", entry.updatedAt)
        putOptional("recipeId", entry.recipeId)
        putOptional("customDish", entry.customDish)
        putOptional("assignedMemberId", entry.assignedMemberId)
        putOptional("cookingTaskId", entry.cookingTaskId)
        putOptional("prepTaskId", entry.prepTaskId)
    }

    fun encodeMenuTemplate(template: ExportMenuTemplate): Map<String, Any?> {
        validateFirestoreId(template.id, "menu_templates id")
        if (template.name.isBlank()) {
            throw MenuFirestoreDocumentCodecException("menu_templates name must not be blank")
        }
        requireNonNegativeLongValue(template.createdAt, "createdAt")
        requireNonNegativeLongValue(template.updatedAt, "updatedAt")
        return linkedMapOf(
            "id" to template.id,
            "name" to template.name,
            "createdAt" to template.createdAt,
            "updatedAt" to template.updatedAt,
        )
    }

    fun encodeMenuTemplateEntry(entry: ExportMenuTemplateEntry): Map<String, Any?> {
        if (entry.cookingTaskId != null) {
            throw MenuFirestoreDocumentCodecException(
                "menu_template_entries cookingTaskId must be absent or null",
            )
        }
        if (entry.prepTaskId != null) {
            throw MenuFirestoreDocumentCodecException(
                "menu_template_entries prepTaskId must be absent or null",
            )
        }
        return buildEncodedMap(
            MENU_TEMPLATE_ENTRY_KEYS - setOf("cookingTaskId", "prepTaskId"),
        ) {
            validateFirestoreId(entry.id, "menu_template_entries id")
            validateReferenceId(entry.templateId, "templateId")
            val dayOfWeek = validateDayOfWeekValue(entry.dayOfWeek, "dayOfWeek")
            val mealType = validateMealTypeValue(entry.mealType, "mealType")
            validateServingsValue(entry.servings, "servings")
            requireNonNegativeLongValue(entry.updatedAt, "updatedAt")
            entry.recipeId?.let { validateReferenceId(it, "recipeId") }
            entry.assignedMemberId?.let { validateReferenceId(it, "assignedMemberId") }
            put("id", entry.id)
            put("templateId", entry.templateId)
            put("dayOfWeek", dayOfWeek)
            put("mealType", mealType)
            put("servings", entry.servings)
            put("updatedAt", entry.updatedAt)
            putOptional("recipeId", entry.recipeId)
            putOptional("customDish", entry.customDish)
            putOptional("assignedMemberId", entry.assignedMemberId)
        }
    }

    fun encodeDailyAssignment(assignment: ExportDailyAssignment): Map<String, Any?> = buildEncodedMap(
        DAILY_ASSIGNMENT_KEYS,
    ) {
        validateFirestoreId(assignment.id, "daily_assignments id")
        requireNonNegativeLongValue(assignment.weekStartMillis, "weekStartMillis")
        val dayOfWeek = validateDayOfWeekValue(assignment.dayOfWeek, "dayOfWeek")
        requireNonNegativeLongValue(assignment.updatedAt, "updatedAt")
        assignment.assignedMemberId?.let { validateReferenceId(it, "assignedMemberId") }
        put("id", assignment.id)
        put("weekStartMillis", assignment.weekStartMillis)
        put("dayOfWeek", dayOfWeek)
        put("isRated", assignment.isRated)
        put("updatedAt", assignment.updatedAt)
        putOptional("assignedMemberId", assignment.assignedMemberId)
        putOptional("rewardPoints", assignment.rewardPoints)
    }

    fun encodeRecord(collection: String, record: Any): Map<String, Any?> = when (collection) {
        DeletedCloudDocumentCollections.WEEKLY_MENUS -> encodeWeeklyMenu(castRecord(record, "weekly_menus"))
        DeletedCloudDocumentCollections.MENU_ENTRIES -> encodeMenuEntry(castRecord(record, "menu_entries"))
        DeletedCloudDocumentCollections.MENU_TEMPLATES -> encodeMenuTemplate(castRecord(record, "menu_templates"))
        DeletedCloudDocumentCollections.MENU_TEMPLATE_ENTRIES ->
            encodeMenuTemplateEntry(castRecord(record, "menu_template_entries"))
        DeletedCloudDocumentCollections.DAILY_ASSIGNMENTS ->
            encodeDailyAssignment(castRecord(record, "daily_assignments"))
        else -> throw MenuFirestoreDocumentCodecException("Unknown menu collection: $collection")
    }

    fun decodeWeeklyMenu(documentId: String, fields: Map<String, Any?>): ExportWeeklyMenu {
        requireAllowedKeys(fields, WEEKLY_MENU_KEYS, "weekly_menus")
        val id = requireIdField(fields, documentId, "weekly_menus")
        return ExportWeeklyMenu(
            id = id,
            startDateMillis = requireNonNegativeLong(fields, "startDateMillis"),
            isAutoGenerated = requireBoolean(fields, "isAutoGenerated"),
            createdAt = requireNonNegativeLong(fields, "createdAt"),
            updatedAt = requireNonNegativeLong(fields, "updatedAt"),
        )
    }

    fun decodeMenuEntry(documentId: String, fields: Map<String, Any?>): ExportMenuEntry {
        requireAllowedKeys(fields, MENU_ENTRY_KEYS, "menu_entries")
        val id = requireIdField(fields, documentId, "menu_entries")
        return ExportMenuEntry(
            id = id,
            menuId = requireReferenceId(fields, "menuId"),
            dayOfWeek = requireDayOfWeek(fields, "dayOfWeek"),
            mealType = requireMealType(fields, "mealType"),
            recipeId = optionalReferenceId(fields, "recipeId"),
            customDish = optionalString(fields, "customDish"),
            servings = requireServings(fields, "servings"),
            assignedMemberId = optionalReferenceId(fields, "assignedMemberId"),
            cookingTaskId = optionalReferenceId(fields, "cookingTaskId"),
            prepTaskId = optionalReferenceId(fields, "prepTaskId"),
            updatedAt = requireNonNegativeLong(fields, "updatedAt"),
        )
    }

    fun decodeMenuTemplate(documentId: String, fields: Map<String, Any?>): ExportMenuTemplate {
        requireAllowedKeys(fields, MENU_TEMPLATE_KEYS, "menu_templates")
        val id = requireIdField(fields, documentId, "menu_templates")
        val name = requireString(fields, "name")
        if (name.isBlank()) {
            throw MenuFirestoreDocumentCodecException("menu_templates name must not be blank")
        }
        return ExportMenuTemplate(
            id = id,
            name = name,
            createdAt = requireNonNegativeLong(fields, "createdAt"),
            updatedAt = requireNonNegativeLong(fields, "updatedAt"),
        )
    }

    fun decodeMenuTemplateEntry(documentId: String, fields: Map<String, Any?>): ExportMenuTemplateEntry {
        requireAllowedKeys(fields, MENU_TEMPLATE_ENTRY_KEYS, "menu_template_entries")
        if (fields["cookingTaskId"] != null) {
            throw MenuFirestoreDocumentCodecException("menu_template_entries cookingTaskId must be absent or null")
        }
        if (fields["prepTaskId"] != null) {
            throw MenuFirestoreDocumentCodecException("menu_template_entries prepTaskId must be absent or null")
        }
        val id = requireIdField(fields, documentId, "menu_template_entries")
        return ExportMenuTemplateEntry(
            id = id,
            templateId = requireReferenceId(fields, "templateId"),
            dayOfWeek = requireDayOfWeek(fields, "dayOfWeek"),
            mealType = requireMealType(fields, "mealType"),
            recipeId = optionalReferenceId(fields, "recipeId"),
            customDish = optionalString(fields, "customDish"),
            servings = requireServings(fields, "servings"),
            assignedMemberId = optionalReferenceId(fields, "assignedMemberId"),
            cookingTaskId = null,
            prepTaskId = null,
            updatedAt = requireNonNegativeLong(fields, "updatedAt"),
        )
    }

    fun decodeDailyAssignment(documentId: String, fields: Map<String, Any?>): ExportDailyAssignment {
        requireAllowedKeys(fields, DAILY_ASSIGNMENT_KEYS, "daily_assignments")
        val id = requireIdField(fields, documentId, "daily_assignments")
        return ExportDailyAssignment(
            id = id,
            weekStartMillis = requireNonNegativeLong(fields, "weekStartMillis"),
            dayOfWeek = requireDayOfWeek(fields, "dayOfWeek"),
            assignedMemberId = optionalReferenceId(fields, "assignedMemberId"),
            rewardPoints = optionalExactInt(fields, "rewardPoints"),
            isRated = requireBoolean(fields, "isRated"),
            updatedAt = requireNonNegativeLong(fields, "updatedAt"),
        )
    }

    private inline fun <reified T> castRecord(record: Any, collection: String): T {
        if (record !is T) {
            throw MenuFirestoreDocumentCodecException(
                "Record type ${record::class.simpleName} does not match collection $collection",
            )
        }
        return record
    }

    private class EncodedMapBuilder(
        private val allowedKeys: Set<String>,
        private val map: LinkedHashMap<String, Any?>,
    ) {
        fun put(key: String, value: Any?) {
            require(key in allowedKeys)
            map[key] = value
        }

        fun putOptional(key: String, value: Any?) {
            if (value != null) {
                put(key, value)
            }
        }
    }

    private fun buildEncodedMap(
        allowedKeys: Set<String>,
        block: EncodedMapBuilder.() -> Unit,
    ): Map<String, Any?> {
        val map = LinkedHashMap<String, Any?>()
        EncodedMapBuilder(allowedKeys, map).block()
        return map
    }

    private fun requireAllowedKeys(fields: Map<String, Any?>, allowedKeys: Set<String>, label: String) {
        val unknown = fields.keys - allowedKeys
        if (unknown.isNotEmpty()) {
            throw MenuFirestoreDocumentCodecException("$label contains unknown fields: $unknown")
        }
    }

    private fun requireIdField(fields: Map<String, Any?>, documentId: String, label: String): String {
        val id = requireString(fields, "id")
        if (id != documentId) {
            throw MenuFirestoreDocumentCodecException("$label id field must match documentId")
        }
        validateFirestoreId(id, "$label id")
        return id
    }

    private fun requireReferenceId(fields: Map<String, Any?>, key: String): String {
        val value = requireString(fields, key)
        validateReferenceId(value, key)
        return value
    }

    private fun optionalReferenceId(fields: Map<String, Any?>, key: String): String? {
        if (!fields.containsKey(key)) return null
        val value = fields[key] ?: return null
        if (value !is String) {
            throw MenuFirestoreDocumentCodecException("$key must be string or null")
        }
        validateReferenceId(value, key)
        return value
    }

    private fun optionalString(fields: Map<String, Any?>, key: String): String? {
        if (!fields.containsKey(key)) return null
        val value = fields[key] ?: return null
        if (value !is String) {
            throw MenuFirestoreDocumentCodecException("$key must be string or null")
        }
        return value
    }

    private fun requireString(fields: Map<String, Any?>, key: String): String {
        val value = fields[key] ?: throw MenuFirestoreDocumentCodecException("Missing required field: $key")
        if (value !is String) {
            throw MenuFirestoreDocumentCodecException("$key must be string")
        }
        return value
    }

    private fun requireBoolean(fields: Map<String, Any?>, key: String): Boolean {
        val value = fields[key] ?: throw MenuFirestoreDocumentCodecException("Missing required field: $key")
        if (value !is Boolean) {
            throw MenuFirestoreDocumentCodecException("$key must be bool")
        }
        return value
    }

    private fun requireNonNegativeLong(fields: Map<String, Any?>, key: String): Long {
        val value = requireInteger(fields, key)
        requireNonNegativeLongValue(value, key)
        return value
    }

    private fun requireNonNegativeLongValue(value: Long, key: String) {
        if (value < 0L) {
            throw MenuFirestoreDocumentCodecException("$key must be >= 0")
        }
    }

    private fun requireDayOfWeek(fields: Map<String, Any?>, key: String): Int {
        val value = requireExactInt(fields, key)
        return validateDayOfWeekValue(value, key)
    }

    private fun requireServings(fields: Map<String, Any?>, key: String): Int {
        val value = requireExactInt(fields, key)
        validateServingsValue(value, key)
        return value
    }

    private fun requireMealType(fields: Map<String, Any?>, key: String): String {
        val value = requireString(fields, key)
        return validateMealTypeValue(value, key)
    }

    private fun optionalExactInt(fields: Map<String, Any?>, key: String): Int? {
        if (!fields.containsKey(key)) return null
        val value = fields[key] ?: return null
        return requireExactIntValue(key, value)
    }

    private fun requireExactInt(fields: Map<String, Any?>, key: String): Int {
        val value = fields[key] ?: throw MenuFirestoreDocumentCodecException("Missing required field: $key")
        return requireExactIntValue(key, value)
    }

    private fun requireInteger(fields: Map<String, Any?>, key: String): Long {
        val value = fields[key] ?: throw MenuFirestoreDocumentCodecException("Missing required field: $key")
        return requireIntegerValue(key, value)
    }

    private fun requireIntegerValue(key: String, value: Any?): Long = when (value) {
        is Long -> value
        is Int -> value.toLong()
        is Double, is Float, is String ->
            throw MenuFirestoreDocumentCodecException("$key must be integer, got ${value::class.simpleName}")
        else -> throw MenuFirestoreDocumentCodecException("$key must be integer")
    }

    private fun requireExactIntValue(key: String, value: Any?): Int {
        val longValue = requireIntegerValue(key, value)
        if (longValue < Int.MIN_VALUE || longValue > Int.MAX_VALUE) {
            throw MenuFirestoreDocumentCodecException("$key is outside Int range")
        }
        return longValue.toInt()
    }

    private fun validateFirestoreId(id: String, label: String) {
        try {
            MenuSyncIds.requireValidFirestoreDocumentId(id)
        } catch (error: IllegalArgumentException) {
            throw MenuFirestoreDocumentCodecException("$label: ${error.message}", error)
        }
    }

    private fun validateReferenceId(value: String, label: String) {
        if (value.isBlank()) {
            throw MenuFirestoreDocumentCodecException("$label must not be blank")
        }
        validateFirestoreId(value, label)
    }

    private fun validateDayOfWeekValue(value: Int, label: String): Int {
        try {
            MenuSyncIds.requireDayOfWeek(value)
        } catch (error: IllegalArgumentException) {
            throw MenuFirestoreDocumentCodecException("$label: ${error.message}", error)
        }
        return value
    }

    private fun validateMealTypeValue(value: String, label: String): String {
        try {
            return MenuSyncIds.requireMealType(value)
        } catch (error: IllegalArgumentException) {
            throw MenuFirestoreDocumentCodecException("$label: ${error.message}", error)
        }
    }

    private fun validateServingsValue(value: Int, label: String) {
        if (value !in 1..99) {
            throw MenuFirestoreDocumentCodecException("$label must be in 1..99")
        }
    }
}
