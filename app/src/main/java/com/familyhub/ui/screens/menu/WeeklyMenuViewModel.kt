    private suspend fun requireFreshCanManageMenu(): Boolean {
        val userId = _state.value.currentUserId
        if (userId.isBlank()) {
            _state.update {
                it.copy(errorMessage = context.getString(R.string.error_no_current_user))
            }
            return false
        }
        return try {
            when (familyMemberDao.getById(userId)?.role) {
                MemberRole.ADMIN, MemberRole.PARENT -> true
                else -> {
                    showReadOnlyRoleError()
                    false
                }
            }
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            _state.update {
                it.copy(
                    errorMessage = UserFacingErrorMapper.message(
                        context,
                        e,
                        UserFacingErrorContext.General,
                        tag = "WeeklyMenuViewModel",
                    ),
                )
            }
            false
        }
    }

