    private suspend fun performMenuUpdate(isAutoGenerated: Boolean, builder: (WeeklyMenu) -> WeeklyMenu): WeeklyMenu {
        if (!requireFreshCanManageMenu()) {
            throw MenuMutationForbiddenException()
        }
        val baseMenu = _state.value.menu?.copy(isAutoGenerated = isAutoGenerated)
            ?: WeeklyMenu(
                id = idGenerator.newId(),
                startDateMillis = _state.value.startOfWeekMillis,
                isAutoGenerated = isAutoGenerated,
                createdAt = TimeUtils.now(),
                entries = emptyList()
            )
        val builtMenu = builder(baseMenu)
        val prepPlan = planSyncPrepTasks(builtMenu)
        weeklyMenuRepository.upsertMenu(_state.value.currentUserId, prepPlan.menu)
        executeDeferredTaskDeletes(prepPlan.taskIdsToDeleteAfterCommit)
        onMenuPersisted(prepPlan.menu)
        return prepPlan.menu
    }

    private suspend fun onMenuPersisted(finalMenu: WeeklyMenu) {
        val currentWeekStart = WeekUtils.getWeekStartMillis(TimeUtils.now())
        if (finalMenu.entries.isEmpty() || finalMenu.startDateMillis != currentWeekStart) {
            mealPlanNotificationManager.cancelTodayNotification()
        } else {
            val recipesById = _state.value.recipes.associateBy { it.id }
            val membersById = _state.value.members.associateBy { it.id }
            when (mealPlanNotificationManager.showTodayPlanNotification(finalMenu, recipesById, membersById)) {
                MealPlanNotificationResult.SHOWN -> Unit
                MealPlanNotificationResult.NO_MENU_FOR_TODAY -> mealPlanNotificationManager.cancelTodayNotification()
                MealPlanNotificationResult.PERMISSION_REQUIRED -> Unit
                MealPlanNotificationResult.NOTIFICATIONS_DISABLED -> mealPlanNotificationManager.cancelTodayNotification()
            }
        }

        val currentHour = TimeUtils.getHourOfDay(TimeUtils.now())
        val prefs = mealPlanPreferencesDataStore.preferencesFlow.firstOrNull()
        val promptHour = prefs?.rewardPromptHour ?: 20
        maybeTriggerRewardPrompt(finalMenu, promptHour)
        FamilyHubWidgetProvider.updateWidgets(context)
    }

    fun shareMenu(format: MenuShareFormat) {
        viewModelScope.launch {
            val menu = _state.value.menu
            if (menu == null || menu.entries.isEmpty()) {
                _state.update {
                    it.copy(errorMessage = context.getString(R.string.menu_share_empty))
                }
                return@launch
            }
            val recipesById = _state.value.recipes.associateBy { it.id }
            val membersById = _state.value.members.associateBy { it.id }
            val result = withContext(Dispatchers.Default) {
                runCatching {
                    mealPlanShareService.createShareIntent(menu, recipesById, membersById, format)
                }
            }
            result.onSuccess { intent ->
                _events.emit(WeeklyMenuEvent.ShareMenu(intent))
            }.onFailure { error ->
                _state.update {
                    it.copy(
                        errorMessage = UserFacingErrorMapper.message(
                            context,
                            error,
                            UserFacingErrorContext.MenuShare,
                            tag = "WeeklyMenuViewModel",
                        ),
                    )
                }
            }
        }
    }

    fun sendTodayMenuNotification() {
        viewModelScope.launch {
            val menu = _state.value.menu
            if (menu == null || menu.entries.isEmpty()) {
                mealPlanNotificationManager.cancelTodayNotification()
                _state.update {
                    it.copy(errorMessage = context.getString(R.string.menu_notification_no_meals_today))
                }
                return@launch
            }
            val recipesById = _state.value.recipes.associateBy { it.id }
            val membersById = _state.value.members.associateBy { it.id }
            when (mealPlanNotificationManager.showTodayPlanNotification(menu, recipesById, membersById)) {
                MealPlanNotificationResult.SHOWN -> {
                    // Успешно отправлено - можно показать сообщение об успехе
                    _events.emit(WeeklyMenuEvent.ShowNotificationError(
                        context.getString(R.string.menu_notification_sent),
                        false
                    ))
                }
                MealPlanNotificationResult.NO_MENU_FOR_TODAY -> {
                    _state.update {
                        it.copy(errorMessage = context.getString(R.string.menu_notification_no_meals_today))
                    }
                }
                MealPlanNotificationResult.PERMISSION_REQUIRED -> {
                    // Эмитим событие для запроса разрешения
                    _events.emit(WeeklyMenuEvent.RequestNotificationPermission)
                }
                MealPlanNotificationResult.NOTIFICATIONS_DISABLED -> {
                    // Эмитим событие для открытия настроек
                    _events.emit(WeeklyMenuEvent.ShowNotificationError(
                        context.getString(R.string.menu_notification_disabled),
                        true
                    ))
                }
            }
        }
    }

    fun retryNotificationAfterPermission() {
        // Повторная попытка после получения разрешения
        sendTodayMenuNotification()
    }

