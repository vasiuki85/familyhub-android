    private fun observeData() {
        viewModelScope.launch {
            val menuFlow = weekStartFlow.flatMapLatest { start ->
                weeklyMenuRepository.observeMenu(start).map { menu -> start to menu }
            }
            val dailyAssignmentsFlow = weekStartFlow.flatMapLatest { start ->
                dailyAssignmentRepository.observeAssignments(start)
            }
            combine(
                recipeRepository.observeRecipes(),
                menuFlow,
                weeklyMenuRepository.observeMenuTemplates(),
                weeklyMenuRepository.observeMenuHistory(),
                appSettingsDataStore.settingsFlow,
                memberRepository.getAllMembers(),
                mealPlanPreferencesDataStore.preferencesFlow,
                dailyAssignmentsFlow
            ) { values: Array<Any?> ->
                @Suppress("UNCHECKED_CAST")
                val recipes = values[0] as List<Recipe>
                val menuPair = values[1] as Pair<Long, WeeklyMenu?>
                val templates = values[2] as List<MenuTemplate>
                val history = values[3] as List<WeeklyMenu>
                val settings = values[4] as com.familyhub.domain.model.AppSettings
                val members = values[5] as List<FamilyMember>
                val preferences = values[6] as MealPlanPreferences
                val assignments = values[7] as List<DailyAssignment>

                val (startOfWeek, menu) = menuPair
                val analytics = buildAnalytics(menu, recipes, members)
                val actorRole = members.firstOrNull { it.id == settings.currentUserId }?.role
                val canManageMenu = actorRole == MemberRole.ADMIN || actorRole == MemberRole.PARENT
                WeeklyMenuUiState(
                    isLoading = false,
                    hasLoadedOnce = true,
                    recipes = recipes,
                    menu = menu,
                    startOfWeekMillis = startOfWeek,
                    errorMessage = null,
                    currentUserId = settings.currentUserId,
                    members = members,
                    history = history,
                    preferences = preferences,
                    dailyAssignments = assignments.associateBy { it.dayOfWeek },
                    analytics = analytics,
                    activeShoppingListId = settings.activeShoppingListId,
                    menuTemplates = templates,
                    canManageMenu = canManageMenu,
                )
            }
                .catch { error ->
                    _state.update {
                        it.copy(
                            isLoading = false,
                            errorMessage = UserFacingErrorMapper.message(
                                context,
                                error,
                                UserFacingErrorContext.Menu,
                                tag = "WeeklyMenuViewModel",
                            ),
                        )
                    }
                }
                .collect { newState ->
                    if (lastRewardPromptWeekStart != newState.startOfWeekMillis) {
                        lastRewardPromptWeekStart = newState.startOfWeekMillis
                        lastRewardPromptDayStart = null
                    }
                    _state.value = newState
                    viewModelScope.launch {
                        maybeTriggerRewardPrompt(newState.menu, newState.preferences.rewardPromptHour)
                    }
                }
        }
    }

