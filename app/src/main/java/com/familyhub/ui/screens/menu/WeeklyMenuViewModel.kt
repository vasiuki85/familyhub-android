    fun generateAutomaticMenu() {
        if (!blockUnlessCanManageMenu()) return
        val recipes = _state.value.recipes
        if (recipes.isEmpty()) {
            _state.update {
                it.copy(errorMessage = context.getString(R.string.menu_generate_error_no_recipes))
            }
            return
        }
        val preferences = _state.value.preferences
        val filtered = recipes.filter { recipe ->
            recipe.prepTimeMinutes <= preferences.maxPrepTimeMinutes &&
                recipe.tags.map { it.lowercase() }.none { tag -> tag in preferences.excludedTags.map { it.lowercase() } }
        }
        val pool = (if (filtered.isNotEmpty()) filtered else recipes).sortedBy { it.prepTimeMinutes }
        if (pool.isEmpty()) {
            _state.update {
                it.copy(errorMessage = context.getString(R.string.menu_generate_error_no_recipes))
            }
            return
        }
        viewModelScope.launch {
            if (!requireFreshCanManageMenu()) return@launch
            val vegetarianTags = setOf("вег", "veg", "vegetarian", "вегетариан")
            val difficultyUsage = mutableMapOf<RecipeDifficulty, Int>()
            val usedThisCycle = mutableSetOf<String>()
            runCatching {
                performMenuUpdate(isAutoGenerated = true) { baseMenu ->
                val entries = mutableListOf<MenuEntry>()
                for (day in 0 until 7) {
                    for (mealType in MealType.values()) {
                        val candidate = selectRecipeForSlot(
                            pool = pool,
                            vegetarianTags = vegetarianTags,
                            preferences = preferences,
                            difficultyUsage = difficultyUsage,
                            usedThisCycle = usedThisCycle
                        )
                        entries.add(
                            MenuEntry(
                                id = idGenerator.newId(),
                                menuId = baseMenu.id,
                                dayOfWeek = day,
                                mealType = mealType,
                                recipeId = candidate.id,
                                customDish = null,
                                servings = if (candidate.servings > 0) candidate.servings else 4,
                                assignedMemberId = null,
                                cookingTaskId = null,
                                prepTaskId = null
                            )
                        )
                    }
                }
                baseMenu.copy(entries = entries)
                }
            }.onFailure { handleMenuMutationFailure(it) }
        }
    }

    private fun selectRecipeForSlot(
        pool: List<Recipe>,
        vegetarianTags: Set<String>,
        preferences: MealPlanPreferences,
        difficultyUsage: MutableMap<RecipeDifficulty, Int>,
        usedThisCycle: MutableSet<String>
    ): Recipe {
        val comparator = compareByDescending<Recipe> { recipe ->
            if (!preferences.preferVegetarian) 0 else if (recipe.tags.any { tag ->
                    vegetarianTags.any { vegTag -> tag.contains(vegTag, ignoreCase = true) }
                }) 1 else 0
        }
            .thenBy { recipe -> difficultyUsage[recipe.difficulty] ?: 0 }
            .thenBy { recipe -> if (recipe.isFavorite) 0 else 1 }
            .thenBy { recipe -> recipe.prepTimeMinutes }

        val available = pool.sortedWith(comparator)
        val candidate = available.firstOrNull { it.id !in usedThisCycle } ?: available.first()
        usedThisCycle.add(candidate.id)
        if (usedThisCycle.size == pool.size) {
            usedThisCycle.clear()
        }
        difficultyUsage[candidate.difficulty] = (difficultyUsage[candidate.difficulty] ?: 0) + 1
        return candidate
    }

    fun setRecipeForMeal(dayOfWeek: Int, mealType: MealType, recipeId: String) {
        if (!blockUnlessCanManageMenu()) return
        val recipe = _state.value.recipes.firstOrNull { it.id == recipeId } ?: return
        viewModelScope.launch {
            if (!requireFreshCanManageMenu()) return@launch
            runCatching {
                performMenuUpdate(isAutoGenerated = false) { menu ->
                    val existingEntries = menu.entries.toMutableList()
                    val index = existingEntries.indexOfFirst { it.dayOfWeek == dayOfWeek && it.mealType == mealType }
                    val existing = existingEntries.getOrNull(index)
                    val entry = (existing ?: MenuEntry(
                        id = idGenerator.newId(),
                        menuId = menu.id,
                        dayOfWeek = dayOfWeek,
                        mealType = mealType,
                        recipeId = recipe.id,
                        customDish = null,
                        servings = if (recipe.servings > 0) recipe.servings else 4,
                        assignedMemberId = null,
                        cookingTaskId = null,
                        prepTaskId = null
                    )).copy(
                        recipeId = recipe.id,
                        customDish = null,
                        servings = if (recipe.servings > 0) recipe.servings else (existing?.servings ?: 4)
                    )
                    if (index >= 0) {
                        existingEntries[index] = entry
                    } else {
                        existingEntries.add(entry)
                    }
                    menu.copy(isAutoGenerated = false, entries = existingEntries)
                }
            }.onFailure { handleMenuMutationFailure(it) }
        }
    }

