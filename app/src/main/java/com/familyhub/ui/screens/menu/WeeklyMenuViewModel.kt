    fun exportWeekToShopping() {
        viewModelScope.launch {
            val currentUserId = _state.value.currentUserId
            if (currentUserId.isBlank()) {
                _state.update {
                    it.copy(errorMessage = context.getString(R.string.error_no_current_user))
                }
                return@launch
            }
            val menu = _state.value.menu ?: return@launch
            val recipes = _state.value.recipes.associateBy { it.id }
            val now = TimeUtils.now()
            val listId = if (_state.value.activeShoppingListId.isNotBlank()) {
                _state.value.activeShoppingListId
            } else {
                shoppingRepository.ensureDefaultList().id
            }
            val existingItems = shoppingRepository.getItemsSnapshot(listId).map { it.title.lowercase() }.toSet()
            val aggregated = menu.entries.mapNotNull { entry ->
                val recipe = entry.recipeId?.let { recipes[it] } ?: return@mapNotNull null
                recipe.ingredients.groupBy { it.name.lowercase() }.map { (key, ingredients) ->
                    val displayName = ingredients.first().name
                    val quantities = ingredients.joinToString(separator = "; ") { ingredient ->
                        val qty = ingredient.quantity.ifBlank { context.getString(R.string.recipes_unknown_quantity) }
                        "$qty (${recipe.title})"
                    }
                    val title = context.getString(R.string.recipes_shopping_item_format, displayName.replaceFirstChar { ch ->
                        if (ch.isLowerCase()) ch.titlecase() else ch.toString()
                    }, quantities)
                    title
                }
            }.flatten()
                .distinct()
                .filterNot { existingItems.contains(it.lowercase()) }

            if (aggregated.isEmpty()) {
                _state.update {
                    it.copy(errorMessage = context.getString(R.string.menu_export_empty))
                }
                return@launch
            }

            val items = aggregated.map { title ->
                com.familyhub.domain.model.ShoppingItem(
                    id = idGenerator.newId(),
                    listId = listId,
                    title = title,
                    createdByUserId = currentUserId,
                    isBought = false,
                    createdAt = now
                )
            }
            runCatching {
                shoppingRepository.upsertItems(items)
                if (_state.value.activeShoppingListId.isBlank()) {
                    appSettingsDataStore.setActiveShoppingList(listId)
                }
            }.onFailure { error ->
                _state.update {
                    it.copy(
                        errorMessage = UserFacingErrorMapper.message(
                            context,
                            error,
                            UserFacingErrorContext.Menu,
                            tag = "WeeklyMenuViewModel",
                        ),
                    )
                }
            }
        }
    }

    fun assignCookingTask(dayOfWeek: Int, mealType: MealType, memberId: String?, customTimeMinutes: Int? = null) {
        if (!blockUnlessCanManageMenu()) return
        viewModelScope.launch {
            if (!requireFreshCanManageMenu()) return@launch
            val state = _state.value
            val currentUserId = state.currentUserId
            if (currentUserId.isBlank()) {
                _state.update {
                    it.copy(errorMessage = context.getString(R.string.error_no_current_user))
                }
                return@launch
            }

            runCatching {
                val menu = state.menu ?: return@launch
                val entry = menu.entries.firstOrNull { it.dayOfWeek == dayOfWeek && it.mealType == mealType } ?: return@launch
                val recipesById = state.recipes.associateBy { it.id }
                val recipe = entry.recipeId?.let { recipesById[it] }
                val dishTitle = recipe?.title ?: entry.customDish ?: context.getString(R.string.menu_custom_meal_label)
                val dueMinutes = customTimeMinutes ?: defaultTimeForMeal(mealType)
                val dueDate = WeekUtils.dayStart(menu.startDateMillis, dayOfWeek) + dueMinutes * 60_000L

                val entryToCleanup = if (memberId.isNullOrBlank()) entry else null
                val updatedEntry = when {
                    memberId.isNullOrBlank() -> {
                        entry.copy(assignedMemberId = null, cookingTaskId = null)
                    }
                    else -> {
                        val existingTask = entry.cookingTaskId?.let { taskRepository.getTaskById(it) }
                        val taskTitle = context.getString(R.string.menu_cook_task_title, dishTitle)
                        val description = recipe?.let {
                            buildString {
                                appendLine(context.getString(R.string.menu_cook_task_description, it.prepTimeMinutes))
                                if (it.notes.isNotBlank()) {
                                    appendLine(it.notes)
                                }
                            }
                        }
                        val task = (existingTask ?: Task(
                            id = idGenerator.newId(),
                            title = taskTitle,
                            description = description,
                            createdByUserId = currentUserId,
                            assignedToUserId = memberId,
                            dueDate = dueDate,
                            repeatRule = RepeatRule.NONE,
                            status = TaskStatus.TODO,
                            createdAt = TimeUtils.now(),
                            orderIndex = existingTask?.orderIndex ?: 0,
                            isPrivate = false,
                            taskType = TaskType.ROUTINE,
                            priority = TaskPriority.MEDIUM,
                            categoryId = null,
                            attachments = emptyList(),
                            comments = emptyList()
                        )).copy(
                            title = taskTitle,
                            description = description,
                            assignedToUserId = memberId,
                            dueDate = dueDate,
                            createdByUserId = currentUserId
                        )
                        taskRepository.upsertTask(task)
                        entry.copy(assignedMemberId = memberId, cookingTaskId = task.id)
                    }
                }
                performMenuUpdate(isAutoGenerated = false) { currentMenu ->
                    val updatedEntries = currentMenu.entries.map { existing ->
                        if (existing.id == updatedEntry.id) updatedEntry else existing
                    }
                    currentMenu.copy(isAutoGenerated = false, entries = updatedEntries)
                }
                if (entryToCleanup != null) {
                    cleanupTasks(entryToCleanup)
                }
            }.onFailure { handleMenuMutationFailure(it) }
        }
    }

    /**
     * Assign a responsible person for the whole day (all meals of the day).
     * If memberId is null, clears assignments and related cooking tasks for that day.
     */
    fun assignResponsibleForDay(dayOfWeek: Int, memberId: String?, customTimeMinutes: Int? = null) {
        if (!blockUnlessCanManageMenu()) return
        viewModelScope.launch {
            if (!requireFreshCanManageMenu()) return@launch
            val state = _state.value
            val currentUserId = state.currentUserId
            if (currentUserId.isBlank()) {
                _state.update {
                    it.copy(errorMessage = context.getString(R.string.error_no_current_user))
                }
                return@launch
            }

            runCatching {
                val existingAssignment = state.dailyAssignments[dayOfWeek]
                val assignment = DailyAssignment(
                    id = existingAssignment?.id ?: idGenerator.newId(),
                    weekStartMillis = state.startOfWeekMillis,
                    dayOfWeek = dayOfWeek,
                    assignedMemberId = memberId
                )
                dailyAssignmentRepository.upsertAssignment(currentUserId, assignment)

                state.menu?.let { menu ->
                    val updatedEntries = menu.entries.map { entry ->
                        if (entry.dayOfWeek != dayOfWeek) return@map entry
                        if (memberId.isNullOrBlank()) {
                            entry.copy(assignedMemberId = null, cookingTaskId = null)
                        } else {
                            val recipesById = state.recipes.associateBy { it.id }
                            val recipe = entry.recipeId?.let { recipesById[it] }
                            val dishTitle = recipe?.title ?: entry.customDish ?: context.getString(R.string.menu_custom_meal_label)
                            val dueMinutes = customTimeMinutes ?: defaultTimeForMeal(entry.mealType)
                            val dueDate = WeekUtils.dayStart(menu.startDateMillis, dayOfWeek) + dueMinutes * 60_000L

                            val existingTask = entry.cookingTaskId?.let { taskRepository.getTaskById(it) }
                            val taskTitle = context.getString(R.string.menu_cook_task_title, dishTitle)
                            val description = recipe?.let {
                                buildString {
                                    appendLine(context.getString(R.string.menu_cook_task_description, it.prepTimeMinutes))
                                    if (it.notes.isNotBlank()) {
                                        appendLine(it.notes)
                                    }
                                }
                            }
                            val task = (existingTask ?: Task(
                                id = idGenerator.newId(),
                                title = taskTitle,
                                description = description,
                                createdByUserId = currentUserId,
                                assignedToUserId = memberId,
                                dueDate = dueDate,
                                repeatRule = RepeatRule.NONE,
                                status = TaskStatus.TODO,
                                createdAt = TimeUtils.now(),
                                orderIndex = existingTask?.orderIndex ?: 0,
                                isPrivate = false,
                                taskType = TaskType.ROUTINE,
                                priority = TaskPriority.MEDIUM,
                                categoryId = null,
                                attachments = emptyList(),
                                comments = emptyList()
                            )).copy(
                                title = taskTitle,
                                description = description,
                                assignedToUserId = memberId,
                                dueDate = dueDate,
                                createdByUserId = currentUserId
                            )
                            taskRepository.upsertTask(task)
                            entry.copy(assignedMemberId = memberId, cookingTaskId = task.id)
                        }
                    }

                    performMenuUpdate(isAutoGenerated = false) { currentMenu ->
                        val merged = currentMenu.entries.map { existing ->
                            updatedEntries.firstOrNull { it.id == existing.id } ?: existing
                        }
                        currentMenu.copy(isAutoGenerated = false, entries = merged)
                    }
                    if (memberId.isNullOrBlank()) {
                        updatedEntries
                            .filter { it.dayOfWeek == dayOfWeek }
                            .forEach { original ->
                                menu.entries.firstOrNull { it.id == original.id }?.let { cleanupTasks(it) }
                            }
                    }
                }
            }.onFailure { handleMenuMutationFailure(it) }
        }
    }

