    fun clearMeal(dayOfWeek: Int, mealType: MealType) {
        if (!blockUnlessCanManageMenu()) return
        viewModelScope.launch {
            if (!requireFreshCanManageMenu()) return@launch
            val menu = _state.value.menu ?: return@launch
            val entry = menu.entries.firstOrNull { it.dayOfWeek == dayOfWeek && it.mealType == mealType }
            runCatching {
                performMenuUpdate(isAutoGenerated = false) { currentMenu ->
                    val filtered = currentMenu.entries.filterNot { it.dayOfWeek == dayOfWeek && it.mealType == mealType }
                    currentMenu.copy(isAutoGenerated = false, entries = filtered)
                }
            }.onSuccess {
                if (entry != null) {
                    cleanupTasks(entry)
                }
            }.onFailure { handleMenuMutationFailure(it) }
        }
    }

