    private suspend fun maybeTriggerRewardPrompt(menu: WeeklyMenu?, rewardPromptHour: Int) {
        if (menu == null) return
        val normalizedHour = rewardPromptHour.coerceIn(0, 23)
        val now = TimeUtils.now()
        val diff = now - menu.startDateMillis
        if (diff < 0) return
        val dayIndex = (diff / MILLIS_PER_DAY).toInt()
        if (dayIndex !in 0..6) return
        val dayStart = WeekUtils.dayStart(menu.startDateMillis, dayIndex)
        val promptTime = dayStart + normalizedHour * MILLIS_PER_HOUR
        if (now < promptTime) return
        if (lastRewardPromptDayStart == dayStart) return
        lastRewardPromptDayStart = dayStart
        markCookingTasksAwaitingApprovalForDay(menu, dayIndex)
    }

    private suspend fun markCookingTasksAwaitingApprovalForDay(menu: WeeklyMenu, dayIndex: Int) {
        val entriesForDay = menu.entries.filter { it.dayOfWeek == dayIndex }
        entriesForDay.forEach { entry ->
            val taskId = entry.cookingTaskId ?: return@forEach
            if (entry.assignedMemberId.isNullOrBlank()) return@forEach
            val task = taskRepository.getTaskById(taskId) ?: return@forEach
            if (task.status == TaskStatus.WAITING_FOR_APPROVAL || task.status == TaskStatus.DONE) return@forEach
            val updated = task.copy(
                status = TaskStatus.WAITING_FOR_APPROVAL,
                requiresApproval = true
            )
            taskRepository.upsertTask(updated)
        }
    }

    /**
     * Plans prep-task menu mutations and applies prep-task upserts.
     *
     * Prep-task deletes are deferred until after menu commit; prep-task creates/updates still run
     * before commit — a known cross-repository atomicity limitation.
     */
    private suspend fun planSyncPrepTasks(menu: WeeklyMenu): MenuPrepTaskPlan {
        if (!requireFreshCanManageMenu()) return MenuPrepTaskPlan(menu, emptySet())
        val recipesById = _state.value.recipes.associateBy { it.id }
        val currentUserId = _state.value.currentUserId
        if (currentUserId.isBlank()) return MenuPrepTaskPlan(menu, emptySet())

        val basePlan = MenuPrepTaskPlanner.plan(menu, recipesById, LONG_PREP_THRESHOLD_MINUTES)
        val updatedEntries = basePlan.menu.entries.map { entry ->
            val recipe = entry.recipeId?.let { recipesById[it] }
            if (recipe == null || recipe.prepTimeMinutes < LONG_PREP_THRESHOLD_MINUTES) {
                entry
            } else {
                val dueDate = WeekUtils.dayStart(menu.startDateMillis, entry.dayOfWeek) -
                    TimeUnit.HOURS.toMillis(PREP_REMINDER_HOURS.toLong())
                val title = context.getString(R.string.menu_prep_task_title, recipe.title)
                val description = context.getString(R.string.menu_prep_task_description, recipe.prepTimeMinutes)
                val existingTask = entry.prepTaskId?.let { taskRepository.getTaskById(it) }
                val task = (existingTask ?: Task(
                    id = idGenerator.newId(),
                    title = title,
                    description = description,
                    createdByUserId = currentUserId,
                    assignedToUserId = entry.assignedMemberId ?: currentUserId,
                    dueDate = dueDate,
                    repeatRule = RepeatRule.NONE,
                    status = TaskStatus.TODO,
                    createdAt = TimeUtils.now(),
                    orderIndex = existingTask?.orderIndex ?: 0,
                    isPrivate = false,
                    taskType = TaskType.ROUTINE,
                    priority = TaskPriority.MEDIUM,
                    categoryId = null,
                    attachments = emptyList(),
                    comments = emptyList()
                )).copy(
                    title = title,
                    description = description,
                    assignedToUserId = entry.assignedMemberId ?: currentUserId,
                    dueDate = dueDate,
                    createdByUserId = currentUserId
                )
                taskRepository.upsertTask(task)
                entry.copy(prepTaskId = task.id)
            }
        }
        return MenuPrepTaskPlan(
            menu = basePlan.menu.copy(entries = updatedEntries),
            taskIdsToDeleteAfterCommit = basePlan.taskIdsToDeleteAfterCommit,
        )
    }

    private suspend fun executeDeferredTaskDeletes(taskIds: Set<String>) {
        if (!requireFreshCanManageMenu()) return
        taskIds.forEach { taskId -> cleanupTaskById(taskId) }
    }

    private suspend fun cleanupTasks(entry: MenuEntry) {
        if (!requireFreshCanManageMenu()) return
        cleanupTaskById(entry.cookingTaskId)
        cleanupTaskById(entry.prepTaskId)
    }

    private suspend fun cleanupTaskById(taskId: String?) {
        if (!requireFreshCanManageMenu()) return
        if (taskId.isNullOrBlank()) return
        taskRepository.getTaskById(taskId)?.let { taskRepository.deleteTask(it) }
    }

    private fun buildAnalytics(menu: WeeklyMenu?, recipes: List<Recipe>, members: List<FamilyMember>): MenuAnalytics {
        if (menu == null) return MenuAnalytics()
        val recipeMap = recipes.associateBy { it.id }
        val assignmentCounts = menu.entries.mapNotNull { it.assignedMemberId }
            .groupingBy { it }
            .eachCount()
        val longPrepMeals = menu.entries.count { entry ->
            val recipe = entry.recipeId?.let { recipeMap[it] }
            recipe != null && recipe.prepTimeMinutes >= LONG_PREP_THRESHOLD_MINUTES
        }
        val favoriteMeals = menu.entries.count { entry ->
            val recipe = entry.recipeId?.let { recipeMap[it] }
            recipe?.isFavorite == true
        }
        return MenuAnalytics(
            assignmentsByMember = assignmentCounts,
            longPrepMeals = longPrepMeals,
            favoriteMeals = favoriteMeals,
            autoGenerated = menu.isAutoGenerated
        )
    }

    private fun defaultTimeForMeal(mealType: MealType): Int {
        return when (mealType) {
            MealType.BREAKFAST -> 8 * 60
            MealType.LUNCH -> 13 * 60
            MealType.DINNER -> 19 * 60
            MealType.SNACK -> 16 * 60
        }
    }
