data class WeeklyMenuUiState(
    val isLoading: Boolean = true,
    /** Отличает первую загрузку от обновления при смене недели: во втором случае контент остаётся на экране. */
    val hasLoadedOnce: Boolean = false,
    val recipes: List<Recipe> = emptyList(),
    val menu: WeeklyMenu? = null,
    val startOfWeekMillis: Long = WeekUtils.getCurrentWeekStartMillis(),
    val errorMessage: String? = null,
    val currentUserId: String = "",
    val members: List<FamilyMember> = emptyList(),
    val history: List<WeeklyMenu> = emptyList(),
    val preferences: MealPlanPreferences = MealPlanPreferences(),
    val dailyAssignments: Map<Int, DailyAssignment> = emptyMap(),
    val analytics: MenuAnalytics = MenuAnalytics(),
    val activeShoppingListId: String = "",
    val menuTemplates: List<MenuTemplate> = emptyList(),
    val canManageMenu: Boolean = false,
) {
    val entriesByDay: Map<Int, List<MenuEntry>>
        get() = menu?.entries?.groupBy { it.dayOfWeek } ?: emptyMap()

    fun entryFor(dayOfWeek: Int, mealType: MealType): MenuEntry? {
        return entriesByDay[dayOfWeek]?.firstOrNull { it.mealType == mealType }
    }
}

